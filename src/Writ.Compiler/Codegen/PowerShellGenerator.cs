using System.Globalization;
using System.Text;
using Writ.Compiler.Ir;

namespace Writ.Compiler.Codegen;

/// <summary>
/// Emits a runnable PowerShell 7 script from the IR. Same IR, same semantics as the C# backend.
/// </summary>
public sealed class PowerShellGenerator
{
    private static readonly HashSet<string> Reserved = new(StringComparer.OrdinalIgnoreCase)
    {
        "input", "args", "error", "host", "null", "true", "false", "matches", "home", "pid", "profile", "pwd",
        "this", "psitem", "_", "foreach", "switch", "sender", "lastexitcode", "stacktrace", "executioncontext",
        "myinvocation", "psboundparameters", "pscmdlet", "psscriptroot", "pscommandpath", "psversiontable",
        "shellid", "ofs", "nestedpromptlevel", "event", "eventargs", "eventsubscriber", "iscoreclr", "islinux",
        "ismacos", "iswindows", "psculture", "psuiculture", "pshome", "psedition", "env", "function", "variable",
        "alias", "local", "script", "global", "private", "using", "workflow"
    };

    private readonly Dictionary<string, IrFunction> _functions = new(StringComparer.Ordinal);
    private readonly Dictionary<string, string> _listConverters = new(StringComparer.Ordinal);
    private readonly StringBuilder _converters = new();

    public static string RuntimeModuleSource
    {
        get
        {
            using var stream = typeof(PowerShellGenerator).Assembly.GetManifestResourceStream("Writ.psm1")
                ?? throw new InvalidOperationException("Writ.psm1 is not embedded.");
            using var reader = new StreamReader(stream);
            return reader.ReadToEnd();
        }
    }

    public string Generate(IrModule module, string? sourcePath = null)
    {
        _functions.Clear();
        _listConverters.Clear();
        _converters.Clear();
        foreach (var function in module.Functions)
        {
            _functions[function.Name] = function;
        }

        var sb = new StringBuilder();
        var entry = module.Functions.FirstOrDefault(f => f.IsEntry);
        var listTools = ListToolsParameter(entry);
        if (entry is not null)
        {
            EmitHelp(sb, module, entry, sourcePath, listTools);
        }
        else
        {
            sb.AppendLine("<#");
            sb.AppendLine($".PARAMETER {listTools}");
            sb.AppendLine("    Lists the MCP tools this script calls, then stops.");
            sb.AppendLine("#>");
        }

        sb.AppendLine("# <auto-generated/>");
        sb.AppendLine("# Generated by Writ compiler");
        if (!string.IsNullOrEmpty(sourcePath))
        {
            sb.AppendLine($"# Source: {sourcePath}");
        }

        sb.AppendLine("#Requires -Version 7");
        // -ListTools is on every script, including ones with no "When run" block.
        sb.AppendLine("[CmdletBinding()]");
        sb.Append("param(");
        var parameters = new List<string>();
        if (entry is not null)
        {
            parameters.AddRange(entry.Parameters.Select(p => $"{TypeAttribute(p.Type)}${Var(p.Name)}"));
        }

        parameters.Add($"[switch]${listTools}");
        sb.Append(string.Join(", ", parameters));
        sb.AppendLine(")");

        sb.AppendLine("Set-StrictMode -Version Latest");
        sb.AppendLine("$ErrorActionPreference = 'Stop'");
        sb.AppendLine("Import-Module (Join-Path $PSScriptRoot 'Writ.psm1') -Force");
        sb.AppendLine("$__IntentWhatIf = if ($env:INTENT_DRY_RUN) { @{ WhatIf = $true } } else { @{} }");
        sb.AppendLine();

        foreach (var type in module.Types)
        {
            EmitType(sb, type);
            sb.AppendLine();
        }

        var body = new StringBuilder();
        foreach (var function in module.Functions)
        {
            EmitFunction(body, function, sourcePath);
            body.AppendLine();
        }

        foreach (var function in module.Functions)
        {
            EmitInvoker(body, function);
            body.AppendLine();
        }

        sb.Append(_converters);
        sb.Append(body);
        // Dot-sourcing (what `writ run` does) only defines the functions. Running the file
        // lists referenced tools when asked, and otherwise runs the entry program.
        sb.AppendLine("if ($MyInvocation.InvocationName -ne '.') {");
        sb.AppendLine($"    if (${listTools}) {{");
        foreach (var tool in ReferencedTools(module))
        {
            sb.AppendLine($"        Write-Output {Quote($"{tool.Alias}.{tool.Operation} ({tool.Transport}) {tool.Endpoint}")}");
        }

        sb.AppendLine("        return");
        sb.AppendLine("    }");
        if (entry is not null)
        {
            sb.Append($"    {Sanitize(entry.Name)}");
            foreach (var parameter in entry.Parameters)
            {
                sb.Append($" -{Var(parameter.Name)} ${Var(parameter.Name)}");
            }

            sb.AppendLine();
        }

        sb.AppendLine("}");

        return sb.ToString();
    }

    /// <summary>A program parameter named ListTools would hide the stock switch, so that name moves aside.</summary>
    private static string ListToolsParameter(IrFunction? entry)
    {
        if (entry is not null && entry.Parameters.Any(p => Var(p.Name).Equals("ListTools", StringComparison.OrdinalIgnoreCase)))
        {
            return "WritListTools";
        }

        return "ListTools";
    }

    private readonly record struct ReferencedTool(string Alias, string Operation, string Transport, string Endpoint);

    /// <summary>MCP calls baked into this script. Listing them does not start a server.</summary>
    private static List<ReferencedTool> ReferencedTools(IrModule module)
    {
        var seen = new HashSet<string>(StringComparer.Ordinal);
        var tools = new List<ReferencedTool>();
        foreach (var function in module.Functions)
        {
            foreach (var step in function.Body)
            {
                Walk(step);
            }
        }

        tools.Sort((a, b) =>
        {
            var byAlias = string.CompareOrdinal(a.Alias, b.Alias);
            return byAlias != 0 ? byAlias : string.CompareOrdinal(a.Operation, b.Operation);
        });
        return tools;

        void Walk(IrNode node)
        {
            switch (node)
            {
                case IrCapabilityCall call:
                    if (call.Provider == "mcp" && seen.Add(call.Alias + "\n" + call.Operation))
                    {
                        tools.Add(new ReferencedTool(
                            call.Alias,
                            call.Operation,
                            string.IsNullOrEmpty(call.Transport) ? "stdio" : call.Transport,
                            call.Endpoint ?? ""));
                    }

                    foreach (var argument in call.Arguments)
                    {
                        Walk(argument.Value);
                    }

                    break;
                case IrAssign assign:
                    Walk(assign.Value);
                    break;
                case IrIf branch:
                    Walk(branch.Condition);
                    foreach (var step in branch.ThenBody) Walk(step);
                    if (branch.OtherwiseBody is not null)
                    {
                        foreach (var step in branch.OtherwiseBody) Walk(step);
                    }

                    break;
                case IrForEach loop:
                    Walk(loop.Collection);
                    foreach (var step in loop.Body) Walk(step);
                    break;
                case IrWhile loop:
                    Walk(loop.Condition);
                    foreach (var step in loop.Body) Walk(step);
                    break;
                case IrTry attempt:
                    foreach (var step in attempt.Body) Walk(step);
                    if (attempt.OnFailure is not null)
                    {
                        foreach (var step in attempt.OnFailure) Walk(step);
                    }

                    if (attempt.Finally is not null)
                    {
                        foreach (var step in attempt.Finally) Walk(step);
                    }

                    break;
                case IrReturn ret:
                    Walk(ret.Value);
                    break;
                case IrCall call:
                    foreach (var argument in call.Arguments) Walk(argument);
                    break;
                case IrFieldAccess access:
                    Walk(access.Target);
                    break;
                case IrListLiteral list:
                    foreach (var element in list.Elements) Walk(element);
                    break;
                case IrBinary binary:
                    Walk(binary.Left);
                    Walk(binary.Right);
                    break;
                case IrUnary unary:
                    Walk(unary.Operand);
                    break;
                case IrSumProjection sum:
                    Walk(sum.Collection);
                    Walk(sum.Projection);
                    break;
                case IrFilter filter:
                    Walk(filter.Collection);
                    Walk(filter.Predicate);
                    break;
                case IrSequence sequence:
                    foreach (var step in sequence.Steps) Walk(step);
                    break;
                case IrSort sort:
                    Walk(sort.Collection);
                    break;
                case IrTake take:
                    Walk(take.Collection);
                    Walk(take.Count);
                    break;
                case IrSelectField select:
                    Walk(select.Collection);
                    break;
                case IrSay say:
                    foreach (var part in say.Parts) Walk(part);
                    break;
                case IrRetry retry:
                    Walk(retry.Operation);
                    break;
                case IrValidate validate:
                    Walk(validate.Value);
                    break;
                case IrScriptCall script:
                    foreach (var argument in script.Arguments) Walk(argument.Value);
                    break;
                case IrCommand command:
                    foreach (var argument in command.Arguments) Walk(argument.Value);
                    break;
            }
        }
    }

    /// <summary>Comment-based help from the program's leading comments and the entry parameters.</summary>
    private void EmitHelp(StringBuilder sb, IrModule module, IrFunction entry, string? sourcePath, string listTools)
    {
        var synopsis = module.Name;
        var description = new List<string>();
        if (!string.IsNullOrEmpty(sourcePath) && File.Exists(sourcePath))
        {
            var leading = File.ReadLines(sourcePath)
                .TakeWhile(line => line.TrimStart().StartsWith('#') || line.Trim().Length == 0)
                .Where(line => line.TrimStart().StartsWith('#'))
                .Select(line => line.TrimStart().TrimStart('#').Trim())
                .ToList();
            if (leading.Count > 0)
            {
                synopsis = leading[0];
                description = leading.Skip(1).ToList();
            }
        }

        sb.AppendLine("<#");
        sb.AppendLine(".SYNOPSIS");
        sb.AppendLine($"    {synopsis}");
        sb.AppendLine(".DESCRIPTION");
        foreach (var line in description.Count > 0 ? description : [$"Compiled from {Path.GetFileName(sourcePath) ?? module.Name + ".writ"} by Writ."])
        {
            sb.AppendLine($"    {line}");
        }

        foreach (var parameter in entry.Parameters)
        {
            sb.AppendLine($".PARAMETER {Var(parameter.Name)}");
            sb.AppendLine($"    {Describe(parameter.Type)}");
        }

        sb.AppendLine($".PARAMETER {listTools}");
        sb.AppendLine("    Lists the MCP tools this script calls, then stops.");

        if (entry.ReturnType is not IrVoidType)
        {
            sb.AppendLine(".OUTPUTS");
            sb.AppendLine($"    {Describe(entry.ReturnType)}");
        }

        sb.AppendLine("#>");
    }

    private static string Describe(IrType type) => type switch
    {
        IrPrimitiveType p => p.Name,
        IrListType l => $"list of {Describe(l.ElementType)}",
        IrRecordType r => r.Name,
        IrDynamicType => "untyped data",
        IrVoidType => "nothing",
        _ => "value"
    };

    private void EmitType(StringBuilder sb, IrTypeDecl type)
    {
        var name = Sanitize(type.Name);
        sb.AppendLine($"class {name} {{");
        foreach (var field in type.Fields)
        {
            sb.AppendLine($"    {TypeAttribute(field.Type)}${Sanitize(field.Name)}");
        }

        sb.AppendLine($"    static [{name}] FromObject($o) {{");
        sb.AppendLine("        if ($null -eq $o) { return $null }");
        sb.AppendLine($"        if ($o -is [{name}]) {{ return $o }}");
        sb.AppendLine($"        $r = [{name}]::new()");
        foreach (var field in type.Fields)
        {
            sb.AppendLine($"        Assert-IntentField -Value $o -Field '{Sanitize(field.Name)}' -TypeName '{name}'");
            sb.AppendLine($"        $r.{Sanitize(field.Name)} = {Convert($"$o.{Sanitize(field.Name)}", field.Type)}");
        }

        sb.AppendLine("        return $r");
        sb.AppendLine("    }");
        sb.AppendLine("}");
    }

    private void EmitFunction(StringBuilder sb, IrFunction function, string? sourcePath)
    {
        if (!string.IsNullOrEmpty(sourcePath))
        {
            sb.AppendLine($"# .writ:{function.Span.StartLine}");
        }

        sb.AppendLine($"function {Sanitize(function.Name)} {{");
        sb.Append("    param(");
        sb.Append(string.Join(", ", function.Parameters.Select(p => $"{TypeAttribute(p.Type)}${Var(p.Name)}")));
        sb.AppendLine(")");
        foreach (var stmt in function.Body)
        {
            EmitStatement(sb, stmt, 1, sourcePath);
        }

        sb.AppendLine("}");
    }

    private void EmitInvoker(StringBuilder sb, IrFunction function)
    {
        sb.AppendLine($"function __Invoke_{Sanitize(function.Name)}($__input) {{");
        foreach (var parameter in function.Parameters)
        {
            sb.AppendLine($"    ${Var(parameter.Name)} = {Convert($"$__input.{Sanitize(parameter.Name)}", parameter.Type)}");
        }

        sb.Append($"    $__result = {Sanitize(function.Name)}");
        foreach (var parameter in function.Parameters)
        {
            sb.Append($" -{Var(parameter.Name)} ${Var(parameter.Name)}");
        }

        sb.AppendLine();
        sb.AppendLine("    return ,$__result");
        sb.AppendLine("}");
    }

    private void EmitStatement(StringBuilder sb, IrNode node, int indent, string? sourcePath)
    {
        var pad = new string(' ', indent * 4);
        switch (node)
        {
            case IrAssign assign:
                if (!string.IsNullOrEmpty(sourcePath))
                {
                    sb.AppendLine($"{pad}# .writ:{assign.Span.StartLine}");
                }

                sb.Append($"{pad}${Var(assign.Name)} = ");
                if (assign.Value is IrListLiteral { Elements.Count: 0 } && assign.Type is IrListType listType)
                {
                    sb.Append($"[{ListTypeName(listType)}]::new()");
                }
                else
                {
                    sb.Append(Expression(assign.Value));
                }

                sb.AppendLine();
                break;

            case IrIf iff:
                sb.AppendLine($"{pad}if ({Expression(iff.Condition)}) {{");
                foreach (var s in iff.ThenBody)
                {
                    EmitStatement(sb, s, indent + 1, sourcePath);
                }

                if (iff.OtherwiseBody is not null)
                {
                    sb.AppendLine($"{pad}}} else {{");
                    foreach (var s in iff.OtherwiseBody)
                    {
                        EmitStatement(sb, s, indent + 1, sourcePath);
                    }
                }

                sb.AppendLine($"{pad}}}");
                break;

            case IrForEach loop:
                sb.AppendLine($"{pad}foreach (${Var(loop.Iterator)} in @({Expression(loop.Collection)})) {{");
                foreach (var s in loop.Body)
                {
                    EmitStatement(sb, s, indent + 1, sourcePath);
                }

                sb.AppendLine($"{pad}}}");
                break;

            case IrReturn ret:
                if (!string.IsNullOrEmpty(sourcePath))
                {
                    sb.AppendLine($"{pad}# .writ:{ret.Span.StartLine}");
                }

                sb.AppendLine(ret.Type is IrListType
                    ? $"{pad}return ,{Expression(ret.Value)}"
                    : $"{pad}return {Expression(ret.Value)}");
                break;

            case IrWhile loop:
                sb.AppendLine($"{pad}while ({Expression(loop.Condition)}) {{");
                foreach (var s in loop.Body)
                {
                    EmitStatement(sb, s, indent + 1, sourcePath);
                }

                sb.AppendLine($"{pad}}}");
                break;

            case IrSay say:
                sb.AppendLine($"{pad}Write-Host (@({string.Join(", ", say.Parts.Select(p => $"(ConvertTo-IntentString -Value {Expression(p)})"))}) -join ' ')");
                break;

            case IrTry tryNode:
                sb.AppendLine($"{pad}try {{");
                foreach (var s in tryNode.Body)
                {
                    EmitStatement(sb, s, indent + 1, sourcePath);
                }

                if (tryNode.OnFailure is not null)
                {
                    sb.AppendLine($"{pad}}} catch {{");
                    sb.AppendLine($"{pad}    ${Var(tryNode.ErrorName)} = [string]$_.Exception.Message");
                    foreach (var s in tryNode.OnFailure)
                    {
                        EmitStatement(sb, s, indent + 1, sourcePath);
                    }
                }

                if (tryNode.Finally is not null)
                {
                    sb.AppendLine($"{pad}}} finally {{");
                    foreach (var s in tryNode.Finally)
                    {
                        EmitStatement(sb, s, indent + 1, sourcePath);
                    }
                }

                sb.AppendLine($"{pad}}}");
                break;

            default:
                sb.AppendLine($"{pad}{Expression(node)} | Out-Null");
                break;
        }
    }

    private string Expression(IrNode node)
    {
        switch (node)
        {
            case IrLiteral lit:
                return Literal(lit);
            case IrVar v:
                return $"${Var(v.Name)}";
            case IrCall call:
                return Call(call);
            case IrFieldAccess field:
                return field.Target is IrVar
                    ? $"{Expression(field.Target)}.{Sanitize(field.FieldName)}"
                    : $"({Expression(field.Target)}).{Sanitize(field.FieldName)}";
            case IrListLiteral list:
            {
                var elementType = list.Type is IrListType lt ? lt.ElementType : IrPrimitiveType.Integer;
                var typeName = ListTypeName(new IrListType(elementType));
                if (list.Elements.Count == 0)
                {
                    return $"[{typeName}]::new()";
                }

                return $"[{typeName}]@({string.Join(", ", list.Elements.Select(Expression))})";
            }
            case IrBinary bin:
                return bin.Operator == "/"
                    ? $"([decimal]{Expression(bin.Left)} / {Expression(bin.Right)})"
                    : $"({Expression(bin.Left)} {Operator(bin.Operator)} {Expression(bin.Right)})";
            case IrUnary unary:
                return unary.Operator == "not"
                    ? $"(-not {Expression(unary.Operand)})"
                    : $"({unary.Operator}{Expression(unary.Operand)})";
            case IrSumProjection sum:
                return $"(Get-IntentSumMap -Items {Expression(sum.Collection)} -Projection {{ param(${Var(sum.Iterator)}) {Expression(sum.Projection)} }})";
            case IrFilter filter:
                return $"(Select-IntentWhere -Items {Expression(filter.Collection)} -Predicate {{ param(${Var(filter.Iterator)}) {Expression(filter.Predicate)} }})";
            case IrCapabilityCall capability:
            {
                var args = string.Join("; ", capability.Arguments.Select(a => $"{Quote(a.Name)} = {Expression(a.Value)}"));
                var provider = capability.Provider == "mock"
                    ? ""
                    : $" -Provider {Quote(capability.Provider)} -Endpoint {Quote(capability.Endpoint ?? "")} -Transport {Quote(string.IsNullOrEmpty(capability.Transport) ? "stdio" : capability.Transport)} -WorkingDirectory {Quote(capability.WorkingDirectory ?? "")}";
                var writes = capability.Effects.Any(e => e is EffectKind.FileSystemWrite or EffectKind.ExternalState or EffectKind.NetworkWrite) ? " -Writes" : "";
                var call = $"(Invoke-WritCapability -Alias {Quote(capability.Alias)} -Operation {Quote(capability.Operation)} -ManifestPath {Quote(capability.ManifestPath)}{provider}{writes} -Arguments @{{ {args} }})";
                return capability.Type is IrListType ? $"@{call}" : call;
            }
            case IrValidate validate:
                return Convert($"({Expression(validate.Value)})", validate.Type);
            case IrRetry retry:
            {
                var call = $"(Invoke-WritRetry -Times {retry.Times} -Action {{ {Expression(retry.Operation)} }})";
                return retry.Type is IrListType ? $"@{call}" : call;
            }
            case IrSort sort:
                return $"@({Expression(sort.Collection)} | Sort-Object -Property {Quote(sort.Field)}{(sort.Descending ? " -Descending" : "")})";
            case IrTake take:
                return $"@({Expression(take.Collection)} | Select-Object -First {Expression(take.Count)})";
            case IrSelectField select:
                return $"@({Expression(select.Collection)} | ForEach-Object {{ $_.{Sanitize(select.Field)} }})";
            case IrScriptCall script:
            {
                var args = string.Join("; ", script.Arguments.Select(a => $"{Quote(a.Name)} = {Expression(a.Value)}"));
                var compiled = script.CompiledScript is null ? "" : $" -Compiled {Quote(script.CompiledScript)}";
                var writes = WritesOnDryRun(script.Effects) ? " -Writes" : "";
                return Convert(
                    $"(Invoke-WritScript -Path {Quote(script.Path)} -Kind {Quote(script.Kind)}{compiled}{writes} -Arguments @{{ {args} }})",
                    script.Type);
            }
            case IrCommand command:
            {
                var sb = new StringBuilder();
                sb.Append(command.Name);
                foreach (var argument in command.Arguments)
                {
                    if (argument.Value is IrLiteral { Value: bool flag })
                    {
                        if (flag)
                        {
                            sb.Append($" -{argument.Name}");
                        }

                        continue;
                    }

                    sb.Append($" -{argument.Name} {Expression(argument.Value)}");
                }

                if (command.Effects.Any(e => e is EffectKind.FileSystemWrite or EffectKind.ExternalState or EffectKind.NetworkWrite))
                {
                    sb.Append(" @__IntentWhatIf");
                }

                return command.Type is IrListType ? $"@({sb})" : $"({sb})";
            }
            case IrSequence sequence:
            {
                var steps = sequence.Steps.Select((step, i) =>
                    i == sequence.Steps.Count - 1 ? Expression(step) : $"{Expression(step)} | Out-Null");
                return $"$({string.Join("; ", steps)})";
            }
            default:
                return "$null";
        }
    }

    private string Call(IrCall call)
    {
        if (call.IsBuiltin)
        {
            var a = call.Arguments.Select(Expression).ToList();
            switch (call.Callee)
            {
                case "len": return $"(Get-IntentLength -Value {a[0]})";
                case "round": return $"(Get-IntentRounded -Value {a[0]} -Digits {a[1]})";
                case "sum": return $"(Get-IntentSum -Values {a[0]})";
                case "append": return $"(Add-IntentItem -List {a[0]} -Item {a[1]})";
                case "str": return $"(ConvertTo-IntentString -Value {a[0]})";
                case "int": return $"(ConvertTo-IntentInteger -Value {a[0]})";
                case "decimal": return $"(ConvertTo-IntentDecimal -Value {a[0]})";
                case "bool": return $"(ConvertTo-IntentBoolean -Value {a[0]})";
                case "json": return $"(ConvertFrom-Json -InputObject {a[0]} -NoEnumerate)";
                case "csv": return $"@(ConvertFrom-Csv -InputObject {a[0]})";
                case "env": return $"([string][Environment]::GetEnvironmentVariable({a[0]}))";
                case "homeFolder": return "([string]$HOME)";
                case "currentFolder": return "([string](Get-Location).Path)";
                case "tempFolder": return "([string][System.IO.Path]::GetTempPath())";
                case "scriptFolder": return "([string]$PSScriptRoot)";
            }
        }

        var sb = new StringBuilder();
        sb.Append('(');
        sb.Append(Sanitize(call.Callee));
        _functions.TryGetValue(call.Callee, out var target);
        for (var i = 0; i < call.Arguments.Count; i++)
        {
            if (target is not null && i < target.Parameters.Count)
            {
                sb.Append($" -{Var(target.Parameters[i].Name)}");
            }

            sb.Append(' ');
            sb.Append(Expression(call.Arguments[i]));
        }

        sb.Append(')');
        return sb.ToString();
    }

    private static string Literal(IrLiteral lit) => lit.Value switch
    {
        null => "$null",
        long l => l < 0 ? $"({l.ToString(CultureInfo.InvariantCulture)}L)" : $"{l.ToString(CultureInfo.InvariantCulture)}L",
        decimal d => d < 0 ? $"({d.ToString(CultureInfo.InvariantCulture)}d)" : $"{d.ToString(CultureInfo.InvariantCulture)}d",
        string s => Quote(s),
        bool b => b ? "$true" : "$false",
        _ => "$null"
    };

    private static string Operator(string op) => op switch
    {
        "and" => "-and",
        "or" => "-or",
        "==" => "-ceq",
        "!=" => "-cne",
        "<" => "-clt",
        "<=" => "-cle",
        ">" => "-cgt",
        ">=" => "-cge",
        _ => op
    };

    private string Convert(string source, IrType type)
    {
        switch (type)
        {
            case IrPrimitiveType { Name: "integer" }:
                return $"[long]{source}";
            case IrPrimitiveType { Name: "decimal" }:
                return $"[decimal]{source}";
            case IrPrimitiveType { Name: "string" }:
                return $"[string]{source}";
            case IrPrimitiveType { Name: "boolean" }:
                return $"[bool]{source}";
            case IrRecordType record:
                return $"[{Sanitize(record.Name)}]::FromObject({source})";
            case IrListType list:
                return $"({ListConverter(list)} {source})";
            default:
                return source;
        }
    }

    private string ListConverter(IrListType list)
    {
        var typeName = ListTypeName(list);
        if (_listConverters.TryGetValue(typeName, out var existing))
        {
            return existing;
        }

        var name = "__ToList_" + new string(typeName.Select(ch => char.IsLetterOrDigit(ch) ? ch : '_').ToArray());
        _listConverters[typeName] = name;
        _converters.AppendLine($"function {name}($o) {{");
        _converters.AppendLine($"    $list = [{typeName}]::new()");
        _converters.AppendLine("    if ($null -eq $o) { return ,$list }");
        _converters.AppendLine("    foreach ($e in @($o)) {");
        _converters.AppendLine($"        [void]$list.Add({Convert("$e", list.ElementType is IrErrorType ? IrPrimitiveType.Decimal : list.ElementType)})");
        _converters.AppendLine("    }");
        _converters.AppendLine("    return ,$list");
        _converters.AppendLine("}");
        _converters.AppendLine();
        return name;
    }

    private static string TypeAttribute(IrType type) => type switch
    {
        IrPrimitiveType => $"[{TypeName(type)}]",
        _ => ""
    };

    public static string TypeName(IrType type) => type switch
    {
        IrPrimitiveType { Name: "integer" } => "long",
        IrPrimitiveType { Name: "decimal" } => "decimal",
        IrPrimitiveType { Name: "string" } => "string",
        IrPrimitiveType { Name: "boolean" } => "bool",
        IrListType list => ListTypeName(list),
        IrRecordType record => Sanitize(record.Name),
        _ => "object"
    };

    private static string ListTypeName(IrListType list) =>
        $"System.Collections.Generic.List[{TypeName(list.ElementType is IrErrorType ? IrPrimitiveType.Decimal : list.ElementType)}]";

    private static bool WritesOnDryRun(IReadOnlyList<EffectKind> effects) =>
        effects.Any(e => e is EffectKind.FileSystemWrite or EffectKind.ExternalState or EffectKind.NetworkWrite or EffectKind.Script or EffectKind.RuntimeAi);

    private static string Quote(string text) => "'" + text.Replace("'", "''") + "'";

    private static string Var(string name)
    {
        var clean = Sanitize(name);
        return Reserved.Contains(clean) ? clean + "_" : clean;
    }

    private static string Sanitize(string name)
    {
        if (string.IsNullOrEmpty(name))
        {
            return "_";
        }

        var chars = name.Select(ch => char.IsLetterOrDigit(ch) || ch == '_' ? ch : '_').ToArray();
        if (char.IsDigit(chars[0]))
        {
            return "_" + new string(chars);
        }

        return new string(chars);
    }
