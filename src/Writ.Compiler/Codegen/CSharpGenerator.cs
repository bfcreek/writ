using System.Globalization;
using System.Text;
using Writ.Compiler.Ir;

namespace Writ.Compiler.Codegen;

public sealed class CSharpGenerator
{
    public string Generate(IrModule module, string? sourcePath = null)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("// Generated by Writ compiler");
        if (!string.IsNullOrEmpty(sourcePath))
        {
            sb.AppendLine($"// Source: {sourcePath}");
        }

        sb.AppendLine("using System;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using Writ.Runtime;");
        sb.AppendLine();
        sb.AppendLine($"namespace Writ.Generated;");
        sb.AppendLine();

        foreach (var type in module.Types)
        {
            EmitType(sb, type);
            sb.AppendLine();
        }

        sb.AppendLine($"public static class {Sanitize(module.Name)}Module");
        sb.AppendLine("{");
        foreach (var function in module.Functions)
        {
            EmitFunction(sb, function, sourcePath);
            sb.AppendLine();
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    private static void EmitType(StringBuilder sb, IrTypeDecl type)
    {
        sb.Append($"public sealed record {Sanitize(type.Name)}(");
        sb.Append(string.Join(", ", type.Fields.Select(f => $"{MapType(f.Type)} {Sanitize(f.Name)}")));
        sb.AppendLine(");");
    }

    private static void EmitFunction(StringBuilder sb, IrFunction function, string? sourcePath)
    {
        if (!string.IsNullOrEmpty(sourcePath))
        {
            sb.AppendLine($"    // .writ:{function.Span.StartLine}");
        }

        sb.Append("    public static ");
        sb.Append(MapType(function.ReturnType));
        sb.Append(' ');
        sb.Append(Sanitize(function.Name));
        sb.Append('(');
        sb.Append(string.Join(", ", function.Parameters.Select(p => $"{MapType(p.Type)} {Sanitize(p.Name)}")));
        sb.AppendLine(")");
        sb.AppendLine("    {");
        foreach (var stmt in function.Body)
        {
            EmitStatement(sb, stmt, 2, sourcePath);
        }

        sb.AppendLine("    }");
    }

    private static void EmitStatement(StringBuilder sb, IrNode node, int indent, string? sourcePath)
    {
        var pad = new string(' ', indent * 4);
        switch (node)
        {
            case IrAssign assign:
                if (!string.IsNullOrEmpty(sourcePath))
                {
                    sb.Append(pad);
                    sb.AppendLine($"// .writ:{assign.Span.StartLine}");
                }

                sb.Append(pad);
                if (assign.IsDeclaration)
                {
                    sb.Append("var ");
                }

                sb.Append(Sanitize(assign.Name));
                sb.Append(" = ");
                if (assign.Value is IrListLiteral { Elements.Count: 0 } && assign.Type is IrListType listType)
                {
                    sb.Append("new List<");
                    sb.Append(MapType(listType.ElementType is IrErrorType ? IrPrimitiveType.Decimal : listType.ElementType));
                    sb.Append(">()");
                }
                else
                {
                    EmitExpression(sb, assign.Value);
                }

                sb.AppendLine(";");
                break;

            case IrIf iff:
                sb.Append(pad);
                sb.Append("if (");
                EmitExpression(sb, iff.Condition);
                sb.AppendLine(")");
                sb.Append(pad);
                sb.AppendLine("{");
                foreach (var s in iff.ThenBody)
                {
                    EmitStatement(sb, s, indent + 1, sourcePath);
                }

                sb.Append(pad);
                sb.AppendLine("}");
                if (iff.OtherwiseBody is not null)
                {
                    sb.Append(pad);
                    sb.AppendLine("else");
                    sb.Append(pad);
                    sb.AppendLine("{");
                    foreach (var s in iff.OtherwiseBody)
                    {
                        EmitStatement(sb, s, indent + 1, sourcePath);
                    }

                    sb.Append(pad);
                    sb.AppendLine("}");
                }

                break;

            case IrForEach loop:
                sb.Append(pad);
                sb.Append("foreach (var ");
                sb.Append(Sanitize(loop.Iterator));
                sb.Append(" in ");
                EmitExpression(sb, loop.Collection);
                sb.AppendLine(")");
                sb.Append(pad);
                sb.AppendLine("{");
                foreach (var s in loop.Body)
                {
                    EmitStatement(sb, s, indent + 1, sourcePath);
                }

                sb.Append(pad);
                sb.AppendLine("}");
                break;

            case IrReturn ret:
                if (!string.IsNullOrEmpty(sourcePath))
                {
                    sb.Append(pad);
                    sb.AppendLine($"// .writ:{ret.Span.StartLine}");
                }

                sb.Append(pad);
                sb.Append("return ");
                EmitExpression(sb, ret.Value);
                sb.AppendLine(";");
                break;

            case IrWhile loop:
                sb.Append(pad);
                sb.Append("while (");
                EmitExpression(sb, loop.Condition);
                sb.AppendLine(")");
                sb.Append(pad);
                sb.AppendLine("{");
                foreach (var s in loop.Body)
                {
                    EmitStatement(sb, s, indent + 1, sourcePath);
                }

                sb.Append(pad);
                sb.AppendLine("}");
                break;

            case IrSay say:
                sb.Append(pad);
                sb.Append("Builtins.Say(");
                for (var i = 0; i < say.Parts.Count; i++)
                {
                    if (i > 0)
                    {
                        sb.Append(", ");
                    }

                    EmitExpression(sb, say.Parts[i]);
                }

                sb.AppendLine(");");
                break;

            case IrTry tryNode:
                sb.Append(pad);
                sb.AppendLine("try");
                sb.Append(pad);
                sb.AppendLine("{");
                foreach (var s in tryNode.Body)
                {
                    EmitStatement(sb, s, indent + 1, sourcePath);
                }

                sb.Append(pad);
                sb.AppendLine("}");
                if (tryNode.OnFailure is not null)
                {
                    sb.Append(pad);
                    sb.AppendLine("catch (Exception __ex)");
                    sb.Append(pad);
                    sb.AppendLine("{");
                    sb.Append(pad);
                    sb.AppendLine($"    var {tryNode.ErrorName} = __ex.Message;");
                    foreach (var s in tryNode.OnFailure)
                    {
                        EmitStatement(sb, s, indent + 1, sourcePath);
                    }

                    sb.Append(pad);
                    sb.AppendLine("}");
                }

                if (tryNode.Finally is not null)
                {
                    sb.Append(pad);
                    sb.AppendLine("finally");
                    sb.Append(pad);
                    sb.AppendLine("{");
                    foreach (var s in tryNode.Finally)
                    {
                        EmitStatement(sb, s, indent + 1, sourcePath);
                    }

                    sb.Append(pad);
                    sb.AppendLine("}");
                }
                break;

            default:
                sb.Append(pad);
                EmitExpression(sb, node);
                sb.AppendLine(";");
                break;
        }
    }

    private static void EmitExpression(StringBuilder sb, IrNode node)
    {
        switch (node)
        {
            case IrLiteral lit:
                EmitLiteral(sb, lit);
                break;
            case IrVar v:
                sb.Append(Sanitize(v.Name));
                break;
            case IrCall call:
                EmitCall(sb, call);
                break;
            case IrFieldAccess field:
                EmitExpression(sb, field.Target);
                sb.Append('.');
                sb.Append(Sanitize(field.FieldName));
                break;
            case IrListLiteral list:
                sb.Append("new List<");
                sb.Append(MapType(list.Type is IrListType lt ? lt.ElementType : IrPrimitiveType.Integer));
                sb.Append("> { ");
                for (var i = 0; i < list.Elements.Count; i++)
                {
                    if (i > 0)
                    {
                        sb.Append(", ");
                    }

                    EmitExpression(sb, list.Elements[i]);
                }

                sb.Append(" }");
                break;
            case IrBinary bin:
                sb.Append('(');
                EmitExpression(sb, bin.Left);
                sb.Append(' ');
                sb.Append(MapOperator(bin.Operator));
                sb.Append(' ');
                EmitExpression(sb, bin.Right);
                sb.Append(')');
                break;
            case IrUnary unary:
                sb.Append('(');
                sb.Append(unary.Operator == "not" ? "!" : unary.Operator);
                EmitExpression(sb, unary.Operand);
                sb.Append(')');
                break;
            case IrSumProjection sum:
                sb.Append("Builtins.SumMap(");
                EmitExpression(sb, sum.Collection);
                sb.Append(", ");
                sb.Append(Sanitize(sum.Iterator));
                sb.Append(" => ");
                EmitExpression(sb, sum.Projection);
                sb.Append(')');
                break;
            case IrFilter filter:
                sb.Append("Builtins.Filter(");
                EmitExpression(sb, filter.Collection);
                sb.Append(", ");
                sb.Append(Sanitize(filter.Iterator));
                sb.Append(" => ");
                EmitExpression(sb, filter.Predicate);
                sb.Append(')');
                break;
            case IrCapabilityCall capability:
                sb.Append("CapabilityRuntime.Call<");
                sb.Append(MapType(capability.Type));
                sb.Append(">(");
                sb.Append(Quote(capability.Alias));
                sb.Append(", ");
                sb.Append(Quote(capability.Operation));
                sb.Append(", ");
                sb.Append(Quote(capability.ManifestPath));
                if (capability.Provider != "mock")
                {
                    sb.Append(", ");
                    sb.Append(Quote(capability.Provider));
                    sb.Append(", ");
                    sb.Append(Quote(capability.Endpoint ?? ""));
                    sb.Append(", ");
                    sb.Append(Quote(capability.WorkingDirectory ?? ""));
                    sb.Append(", ");
                    sb.Append(Quote(string.IsNullOrEmpty(capability.Transport) ? "stdio" : capability.Transport));
                }

                sb.Append(", arguments: new Dictionary<string, object> { ");
                for (var i = 0; i < capability.Arguments.Count; i++)
                {
                    if (i > 0)
                    {
                        sb.Append(", ");
                    }

                    sb.Append('[');
                    sb.Append(Quote(capability.Arguments[i].Name));
                    sb.Append("] = ");
                    EmitExpression(sb, capability.Arguments[i].Value);
                }

                sb.Append(" })");
                break;
            case IrValidate validate:
                sb.Append($"Builtins.Shape<{MapType(validate.Type)}>(");
                EmitExpression(sb, validate.Value);
                sb.Append(')');
                break;
            case IrRetry retry:
                sb.Append($"Builtins.Retry({retry.Times}, () => ");
                EmitExpression(sb, retry.Operation);
                sb.Append(')');
                break;
            case IrSort sort:
                sb.Append("Builtins.SortBy(");
                EmitExpression(sb, sort.Collection);
                sb.Append($", __x => __x.{Sanitize(sort.Field)}, {(sort.Descending ? "true" : "false")})");
                break;
            case IrTake take:
                sb.Append("Builtins.Take(");
                EmitExpression(sb, take.Collection);
                sb.Append(", ");
                EmitExpression(sb, take.Count);
                sb.Append(')');
                break;
            case IrSelectField select:
                sb.Append("Builtins.Select(");
                EmitExpression(sb, select.Collection);
                sb.Append($", __x => __x.{Sanitize(select.Field)})");
                break;
            case IrScriptCall script:
            {
                var resultType = script.Type is IrVoidType ? "object" : MapType(script.Type);
                sb.Append($"ScriptRuntime.Run<{resultType}>(");
                sb.Append(Quote(script.Path));
                sb.Append(", ");
                sb.Append(Quote(script.Kind));
                sb.Append(", ");
                sb.Append(script.CompiledScript is null ? "null" : Quote(script.CompiledScript));
                sb.Append(", ");
                sb.Append(WritesOnDryRun(script.Effects) ? "true" : "false");
                sb.Append(", new Dictionary<string, object> { ");
                for (var i = 0; i < script.Arguments.Count; i++)
                {
                    if (i > 0)
                    {
                        sb.Append(", ");
                    }

                    sb.Append('[');
                    sb.Append(Quote(script.Arguments[i].Name));
                    sb.Append("] = ");
                    EmitExpression(sb, script.Arguments[i].Value);
                }

                sb.Append(" })");
                break;
            }
            case IrCommand command:
                sb.Append($"throw new NotSupportedException(\"'{command.Name}' is a PowerShell command; compile with --target powershell.\")");
                break;
            case IrSequence sequence:
                sb.Append("((Func<");
                sb.Append(MapType(sequence.Type));
                sb.Append(">)(() => { ");
                for (var i = 0; i < sequence.Steps.Count; i++)
                {
                    if (i == sequence.Steps.Count - 1)
                    {
                        sb.Append("return ");
                    }

                    EmitExpression(sb, sequence.Steps[i]);
                    sb.Append("; ");
                }

                sb.Append("}))()");
                break;
            default:
                sb.Append("default!");
                break;
        }
    }

    private static void EmitCall(StringBuilder sb, IrCall call)
    {
        if (call.IsBuiltin)
        {
            switch (call.Callee)
            {
                case "len":
                    sb.Append("Builtins.Len(");
                    EmitExpression(sb, call.Arguments[0]);
                    sb.Append(')');
                    return;
                case "round":
                    sb.Append("Builtins.Round(");
                    EmitExpression(sb, call.Arguments[0]);
                    sb.Append(", ");
                    EmitExpression(sb, call.Arguments[1]);
                    sb.Append(')');
                    return;
                case "sum":
                    sb.Append("Builtins.Sum(");
                    EmitExpression(sb, call.Arguments[0]);
                    sb.Append(')');
                    return;
                case "append":
                    sb.Append("Builtins.Append(");
                    EmitExpression(sb, call.Arguments[0]);
                    sb.Append(", ");
                    EmitExpression(sb, call.Arguments[1]);
                    sb.Append(')');
                    return;
                case "str":
                    sb.Append("Builtins.Str(");
                    EmitExpression(sb, call.Arguments[0]);
                    sb.Append(')');
                    return;
                case "int":
                    sb.Append("Builtins.Int(");
                    EmitExpression(sb, call.Arguments[0]);
                    sb.Append(')');
                    return;
                case "decimal":
                    sb.Append("Builtins.Dec(");
                    EmitExpression(sb, call.Arguments[0]);
                    sb.Append(')');
                    return;
                case "bool":
                    sb.Append("Builtins.Bool(");
                    EmitExpression(sb, call.Arguments[0]);
                    sb.Append(')');
                    return;
                case "json":
                    sb.Append("Builtins.ParseJson(");
                    EmitExpression(sb, call.Arguments[0]);
                    sb.Append(')');
                    return;
                case "csv":
                    sb.Append("Builtins.ParseCsv(");
                    EmitExpression(sb, call.Arguments[0]);
                    sb.Append(')');
                    return;
                case "env":
                    sb.Append("Builtins.Env(");
                    EmitExpression(sb, call.Arguments[0]);
                    sb.Append(')');
                    return;
                case "homeFolder":
                    sb.Append("Builtins.HomeFolder()");
                    return;
                case "currentFolder":
                    sb.Append("Builtins.CurrentFolder()");
                    return;
                case "tempFolder":
                    sb.Append("Builtins.TempFolder()");
                    return;
                case "scriptFolder":
                    sb.Append("Builtins.CurrentFolder()");
                    return;
            }
        }

        sb.Append(Sanitize(call.Callee));
        sb.Append('(');
        for (var i = 0; i < call.Arguments.Count; i++)
        {
            if (i > 0)
            {
                sb.Append(", ");
            }

            EmitExpression(sb, call.Arguments[i]);
        }

        sb.Append(')');
    }

    private static void EmitLiteral(StringBuilder sb, IrLiteral lit)
    {
        switch (lit.Value)
        {
            case null:
                sb.Append("null");
                break;
            case long l:
                sb.Append(l.ToString(CultureInfo.InvariantCulture));
                sb.Append('L');
                break;
            case decimal d:
                sb.Append(d.ToString(CultureInfo.InvariantCulture));
                sb.Append('m');
                break;
            case string s:
                sb.Append('"');
                sb.Append(s.Replace("\\", "\\\\").Replace("\"", "\\\""));
                sb.Append('"');
                break;
            case bool b:
                sb.Append(b ? "true" : "false");
                break;
            default:
                sb.Append("default!");
                break;
        }
    }

    private static string MapOperator(string op) => op switch
    {
        "and" => "&&",
        "or" => "||",
        "==" => "==",
        "!=" => "!=",
        _ => op
    };

    private static string MapType(IrType type) => type switch
    {
        IrPrimitiveType { Name: "integer" } => "long",
        IrPrimitiveType { Name: "decimal" } => "decimal",
        IrPrimitiveType { Name: "string" } => "string",
        IrPrimitiveType { Name: "boolean" } => "bool",
        IrListType list => $"List<{MapType(list.ElementType is IrErrorType ? IrPrimitiveType.Decimal : list.ElementType)}>",
        IrRecordType record => Sanitize(record.Name),
        IrVoidType => "void",
        IrErrorType => "object",
        IrDynamicType => "object",
        _ => "object"
    };

    private static bool WritesOnDryRun(IReadOnlyList<EffectKind> effects) =>
        effects.Any(e => e is EffectKind.FileSystemWrite or EffectKind.ExternalState or EffectKind.NetworkWrite or EffectKind.Script or EffectKind.RuntimeAi);

    private static string Quote(string text) =>
        "\"" + text
            .Replace("\\", "\\\\")
            .Replace("\"", "\\\"")
            .Replace("\r", "\\r")
            .Replace("\n", "\\n")
            .Replace("\t", "\\t") + "\"";

    private static string Sanitize(string name)
    {
        if (string.IsNullOrEmpty(name))
        {
            return "_";
        }

        var sb = new StringBuilder();
        foreach (var ch in name)
        {
            sb.Append(char.IsLetterOrDigit(ch) || ch == '_' ? ch : '_');
        }

        if (char.IsDigit(sb[0]))
        {
            sb.Insert(0, '_');
        }

        return sb.ToString();
    }
}
