using System.Globalization;
using System.Text;
using Writ.Compiler.Ir;

namespace Writ.Compiler.Codegen;

/// <summary>
/// Emits a C# static class from the IR subset a terminal kernel needs.
/// Programs outside that subset are refused by <see cref="Unsupported"/>.
/// </summary>
public sealed class CSharpGenerator
{
    private static readonly HashSet<string> Keywords = new(StringComparer.Ordinal)
    {
        "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked", "class", "const",
        "continue", "decimal", "default", "delegate", "do", "double", "else", "enum", "event", "explicit", "extern",
        "false", "finally", "fixed", "float", "for", "foreach", "goto", "if", "implicit", "in", "int", "interface",
        "internal", "is", "lock", "long", "namespace", "new", "null", "object", "operator", "out", "override",
        "params", "private", "protected", "public", "readonly", "ref", "return", "sbyte", "sealed", "short",
        "sizeof", "stackalloc", "static", "string", "struct", "switch", "this", "throw", "true", "try", "typeof",
        "uint", "ulong", "unchecked", "unsafe", "ushort", "using", "virtual", "void", "volatile", "while",
        "record", "init", "nint", "nuint", "required", "file", "scoped"
    };

    private static readonly HashSet<string> Builtins = new(StringComparer.Ordinal)
    {
        "len", "round", "sum", "append", "str", "int", "decimal", "bool"
    };

    /// <summary>
    /// Why this module cannot be a C# library, or null when it can.
    /// The reason starts with "calls " so emission selection can tell a blocker from a constraint.
    /// </summary>
    public static string? Unsupported(IrModule module)
    {
        if (module.Types.Count > 0)
        {
            return "calls a declared type";
        }

        if (module.Usings.Count > 0)
        {
            return "calls a using";
        }

        foreach (var function in module.Functions)
        {
            if (function.IsFilter || function.IsMethod || function.CmdletBinding)
            {
                return $"calls {function.Name}";
            }

            if (function.Parameters.Any(parameter =>
                    parameter.Default is not null || parameter.FromPipeline || parameter.OneOf is not null ||
                    parameter.ScopeOrPattern()))
            {
                return $"calls {function.Name}";
            }

            foreach (var step in function.Body)
            {
                var why = Visit(step);
                if (why is not null)
                {
                    return why;
                }
            }
        }

        return null;
    }

    public string Generate(IrModule module, string? sourcePath = null)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("// Generated by Writ compiler");
        if (!string.IsNullOrEmpty(sourcePath))
        {
            sb.AppendLine($"// Source: {sourcePath}");
        }

        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("public static class WritProgram");
        sb.AppendLine("{");
        foreach (var function in module.Functions)
        {
            EmitFunction(sb, function);
            sb.AppendLine();
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    private static void EmitFunction(StringBuilder sb, IrFunction function)
    {
        if (function.IsEntry)
        {
            sb.AppendLine("    [global::Writ.Runtime.MachineEntry]");
        }

        sb.Append("    public static ");
        sb.Append(CsType(function.ReturnType));
        sb.Append(' ');
        sb.Append(Ident(function.Name));
        sb.Append('(');
        sb.Append(string.Join(", ", function.Parameters.Select(parameter => $"{CsType(parameter.Type)} {Ident(parameter.Name)}")));
        sb.AppendLine(")");
        sb.AppendLine("    {");

        var locals = Locals(function);
        foreach (var local in locals)
        {
            sb.AppendLine($"        {CsType(local.Type)} {Ident(local.Name)} = {DefaultValue(local.Type)};");
        }

        foreach (var step in function.Body)
        {
            EmitStatement(sb, step, 2);
        }

        sb.AppendLine("    }");
    }

    private static List<(string Name, IrType Type)> Locals(IrFunction function)
    {
        var loopNames = new HashSet<string>(StringComparer.Ordinal);
        CollectLoopNames(function.Body, loopNames);
        var seen = new HashSet<string>(StringComparer.Ordinal);
        var locals = new List<(string Name, IrType Type)>();
        foreach (var parameter in function.Parameters)
        {
            seen.Add(parameter.Name);
        }

        CollectLocals(function.Body, loopNames, seen, locals);
        return locals;
    }

    private static void CollectLoopNames(IReadOnlyList<IrNode> body, HashSet<string> names)
    {
        foreach (var node in body)
        {
            switch (node)
            {
                case IrForEach loop:
                    names.Add(loop.Iterator);
                    CollectLoopNames(loop.Body, names);
                    break;
                case IrFor loop:
                    names.Add(loop.Name);
                    CollectLoopNames(loop.Body, names);
                    break;
                case IrIf branch:
                    CollectLoopNames(branch.ThenBody, names);
                    if (branch.OtherwiseBody is not null)
                    {
                        CollectLoopNames(branch.OtherwiseBody, names);
                    }

                    break;
                case IrWhile loop:
                    CollectLoopNames(loop.Body, names);
                    break;
            }
        }
    }

    private static void CollectLocals(
        IReadOnlyList<IrNode> body,
        HashSet<string> loopNames,
        HashSet<string> seen,
        List<(string Name, IrType Type)> locals)
    {
        foreach (var node in body)
        {
            switch (node)
            {
                case IrAssign assign when seen.Add(assign.Name) && !loopNames.Contains(assign.Name):
                    locals.Add((assign.Name, assign.Type));
                    break;
                case IrIf branch:
                    CollectLocals(branch.ThenBody, loopNames, seen, locals);
                    if (branch.OtherwiseBody is not null)
                    {
                        CollectLocals(branch.OtherwiseBody, loopNames, seen, locals);
                    }

                    break;
                case IrWhile loop:
                    CollectLocals(loop.Body, loopNames, seen, locals);
                    break;
                case IrForEach loop:
                    CollectLocals(loop.Body, loopNames, seen, locals);
                    break;
                case IrFor loop:
                    CollectLocals(loop.Body, loopNames, seen, locals);
                    break;
            }
        }
    }

    private static void EmitStatement(StringBuilder sb, IrNode node, int indent)
    {
        var pad = new string(' ', indent * 4);
        switch (node)
        {
            case IrAssign assign:
                sb.AppendLine($"{pad}{Ident(assign.Name)} = {Expr(assign.Value)};");
                break;
            case IrIf branch:
                sb.AppendLine($"{pad}if ({Expr(branch.Condition)})");
                sb.AppendLine($"{pad}{{");
                foreach (var step in branch.ThenBody)
                {
                    EmitStatement(sb, step, indent + 1);
                }

                if (branch.OtherwiseBody is not null)
                {
                    sb.AppendLine($"{pad}}}");
                    sb.AppendLine($"{pad}else");
                    sb.AppendLine($"{pad}{{");
                    foreach (var step in branch.OtherwiseBody)
                    {
                        EmitStatement(sb, step, indent + 1);
                    }
                }

                sb.AppendLine($"{pad}}}");
                break;
            case IrWhile loop:
                sb.AppendLine($"{pad}while ({Expr(loop.Condition)})");
                sb.AppendLine($"{pad}{{");
                foreach (var step in loop.Body)
                {
                    EmitStatement(sb, step, indent + 1);
                }

                sb.AppendLine($"{pad}}}");
                break;
            case IrForEach loop:
                sb.AppendLine($"{pad}foreach ({ElementType(loop.Collection.Type)} {Ident(loop.Iterator)} in {Expr(loop.Collection)})");
                sb.AppendLine($"{pad}{{");
                foreach (var step in loop.Body)
                {
                    EmitStatement(sb, step, indent + 1);
                }

                sb.AppendLine($"{pad}}}");
                break;
            case IrFor loop:
                var name = Ident(loop.Name);
                sb.AppendLine($"{pad}for ({CsType(loop.From.Type)} {name} = {Expr(loop.From)}; {name} <= {Expr(loop.To)}; {name}++)");
                sb.AppendLine($"{pad}{{");
                foreach (var step in loop.Body)
                {
                    EmitStatement(sb, step, indent + 1);
                }

                sb.AppendLine($"{pad}}}");
                break;
            case IrReturn ret:
                sb.AppendLine(ret.Type is IrVoidType
                    ? $"{pad}return;"
                    : $"{pad}return {Expr(ret.Value)};");
                break;
            case IrSay say:
                sb.AppendLine($"{pad}global::Writ.Runtime.Machine.Say(string.Join(\" \", new string[] {{ {string.Join(", ", say.Parts.Select(part => $"global::Writ.Runtime.Machine.Text({Expr(part)})"))} }}));");
                break;
            case IrCommand command:
                sb.AppendLine($"{pad}{Command(command)};");
                break;
            case IrCall call:
                sb.AppendLine($"{pad}{Call(call)};");
                break;
            default:
                throw new InvalidOperationException($"Cannot emit {node.GetType().Name}.");
        }
    }

    private static string Expr(IrNode node) => node switch
    {
        IrLiteral literal => Literal(literal),
        IrVar variable => Ident(variable.Name),
        IrCall call => Call(call),
        IrListLiteral list => List(list),
        IrBinary binary => Binary(binary),
        IrUnary unary => unary.Operator == "not" ? $"(!({Expr(unary.Operand)}))" : $"(-({Expr(unary.Operand)}))",
        IrCommand command => Command(command),
        _ => throw new InvalidOperationException($"Cannot emit {node.GetType().Name}.")
    };

    private static string Call(IrCall call)
    {
        var args = call.Arguments.Select(Expr).ToList();
        if (call.IsBuiltin)
        {
            return call.Callee switch
            {
                "len" => $"global::Writ.Runtime.Machine.Len({args[0]})",
                "round" => $"global::Writ.Runtime.Machine.Round({args[0]}, {args[1]})",
                "sum" => $"global::Writ.Runtime.Machine.Sum({args[0]})",
                "append" => $"global::Writ.Runtime.Machine.Append({args[0]}, {args[1]})",
                "str" => $"global::Writ.Runtime.Machine.Text({args[0]})",
                "int" => $"global::Writ.Runtime.Machine.ToInteger({args[0]})",
                "decimal" => $"global::Writ.Runtime.Machine.ToDecimal({args[0]})",
                "bool" => $"global::Writ.Runtime.Machine.ToBoolean({args[0]})",
                _ => throw new InvalidOperationException($"Cannot emit builtin {call.Callee}.")
            };
        }

        return $"{Ident(call.Callee)}({string.Join(", ", args)})";
    }

    private static string Command(IrCommand command)
    {
        string? Arg(string name) => command.Arguments.FirstOrDefault(argument => argument.Name == name) is { } found
            ? Expr(found.Value)
            : null;

        return command.Name switch
        {
            "Clear-Host" => "global::Writ.Runtime.Machine.Clear()",
            "Read-Host" => $"global::Writ.Runtime.Machine.Read({Arg("Prompt") ?? "null"})",
            "Start-Sleep" when Arg("Milliseconds") is { } milliseconds => $"global::Writ.Runtime.Machine.Wait({milliseconds}, true)",
            "Start-Sleep" when Arg("Seconds") is { } seconds => $"global::Writ.Runtime.Machine.Wait({seconds}, false)",
            _ => throw new InvalidOperationException($"Cannot emit {command.Name}.")
        };
    }

    private static string List(IrListLiteral list)
    {
        var type = CsType(list.Type);
        if (list.Elements.Count == 0)
        {
            return $"new {type}()";
        }

        return $"new {type} {{ {string.Join(", ", list.Elements.Select(Expr))} }}";
    }

    private static string Binary(IrBinary binary)
    {
        if (binary.Operator == "+" && binary.Left.Type is IrListType && binary.Right.Type is IrListType)
        {
            return $"global::Writ.Runtime.Machine.Concat({Expr(binary.Left)}, {Expr(binary.Right)})";
        }

        if (binary.Type is IrPrimitiveType { Name: "string" })
        {
            return $"(global::Writ.Runtime.Machine.Text({Expr(binary.Left)}) + global::Writ.Runtime.Machine.Text({Expr(binary.Right)}))";
        }

        var op = binary.Operator switch
        {
            "and" => "&&",
            "or" => "||",
            _ => binary.Operator
        };
        if (binary.Type is IrPrimitiveType { Name: "decimal" } && op is "+" or "-" or "*" or "/" or "%")
        {
            return $"((decimal)({Expr(binary.Left)}) {op} (decimal)({Expr(binary.Right)}))";
        }

        return $"({Expr(binary.Left)} {op} {Expr(binary.Right)})";
    }

    private static string Literal(IrLiteral literal) => literal.Value switch
    {
        null => "null",
        long number => number < 0 ? $"({number.ToString(CultureInfo.InvariantCulture)}L)" : $"{number.ToString(CultureInfo.InvariantCulture)}L",
        int number => number < 0 ? $"({number.ToString(CultureInfo.InvariantCulture)}L)" : $"{number.ToString(CultureInfo.InvariantCulture)}L",
        decimal number => DecimalLiteral(number),
        string text => Quote(text),
        bool flag => flag ? "true" : "false",
        _ => throw new InvalidOperationException($"Cannot emit literal {literal.Value}.")
    };

    private static string DecimalLiteral(decimal number)
    {
        var text = number.ToString(CultureInfo.InvariantCulture);
        var literal = text.IndexOfAny(['.', 'E', 'e']) >= 0 ? text + "m" : text + "m";
        return number < 0 ? $"({literal})" : literal;
    }

    private static string Quote(string text)
    {
        var sb = new StringBuilder("\"");
        foreach (var ch in text)
        {
            switch (ch)
            {
                case '\\':
                    sb.Append("\\\\");
                    break;
                case '"':
                    sb.Append("\\\"");
                    break;
                case '\n':
                    sb.Append("\\n");
                    break;
                case '\r':
                    sb.Append("\\r");
                    break;
                case '\t':
                    sb.Append("\\t");
                    break;
                default:
                    if (char.IsControl(ch))
                    {
                        sb.Append("\\u");
                        sb.Append(((int)ch).ToString("x4", CultureInfo.InvariantCulture));
                    }
                    else
                    {
                        sb.Append(ch);
                    }

                    break;
            }
        }

        sb.Append('"');
        return sb.ToString();
    }

    private static string? Visit(IrNode node)
    {
        if (node.Type is IrRecordType or IrDynamicType)
        {
            return "calls a type this library does not emit";
        }

        switch (node)
        {
            case IrAssign assign:
                if (assign.Operator != "=" || !string.IsNullOrEmpty(assign.Scope) || assign.Option is not null)
                {
                    return "calls an assignment this library does not emit";
                }

                return Visit(assign.Value);
            case IrIf branch:
                return Visit(branch.Condition) ?? VisitAll(branch.ThenBody) ?? VisitAll(branch.OtherwiseBody);
            case IrWhile loop:
                return Visit(loop.Condition) ?? VisitAll(loop.Body);
            case IrForEach loop:
                return Visit(loop.Collection) ?? VisitAll(loop.Body);
            case IrFor loop:
                return Visit(loop.From) ?? Visit(loop.To) ?? VisitAll(loop.Body);
            case IrReturn ret:
                return ret.Type is IrVoidType ? null : Visit(ret.Value);
            case IrSay say:
                return VisitAll(say.Parts);
            case IrLiteral:
                return null;
            case IrVar variable:
                if (!string.IsNullOrEmpty(variable.Scope) || variable.Name is "this" or "pipelineItem" or "arguments" or "errors" or "succeeded")
                {
                    return $"calls {variable.Name}";
                }

                return null;
            case IrCall call:
                if (call.IsBuiltin && !Builtins.Contains(call.Callee))
                {
                    return $"calls {call.Callee}";
                }

                return VisitAll(call.Arguments);
            case IrListLiteral list:
                return VisitAll(list.Elements);
            case IrBinary binary:
                if (binary.Operator is not ("+" or "-" or "*" or "/" or "%" or "==" or "!=" or "<" or "<=" or ">" or ">=" or "and" or "or"))
                {
                    return $"calls operator {binary.Operator}";
                }

                if (binary.Operator == "*" && (binary.Left.Type is IrListType or IrPrimitiveType { Name: "string" }))
                {
                    return "calls repetition";
                }

                return Visit(binary.Left) ?? Visit(binary.Right);
            case IrUnary unary:
                if (unary.Operator is not ("not" or "-"))
                {
                    return $"calls operator {unary.Operator}";
                }

                return Visit(unary.Operand);
            case IrCommand command:
                if (command.Name is not ("Clear-Host" or "Read-Host" or "Start-Sleep"))
                {
                    return $"calls {command.Name}";
                }

                return VisitAll(command.Arguments.Select(argument => argument.Value));
            default:
                return $"calls {node.GetType().Name}";
        }
    }

    private static string? VisitAll(IEnumerable<IrNode>? nodes)
    {
        if (nodes is null)
        {
            return null;
        }

        foreach (var node in nodes)
        {
            var why = Visit(node);
            if (why is not null)
            {
                return why;
            }
        }

        return null;
    }

    private static string ElementType(IrType type) =>
        type is IrListType list ? CsType(list.ElementType) : "object";

    private static string CsType(IrType type) => type switch
    {
        IrPrimitiveType { Name: "integer" } => "long",
        IrPrimitiveType { Name: "decimal" } => "decimal",
        IrPrimitiveType { Name: "string" } => "string",
        IrPrimitiveType { Name: "boolean" } => "bool",
        IrListType list => $"global::System.Collections.Generic.List<{CsType(list.ElementType)}>",
        IrVoidType => "void",
        _ => "object"
    };

    private static string DefaultValue(IrType type) => type switch
    {
        IrListType => $"new {CsType(type)}()",
        IrPrimitiveType { Name: "string" } => "\"\"",
        IrPrimitiveType { Name: "boolean" } => "false",
        IrPrimitiveType { Name: "decimal" } => "0m",
        IrPrimitiveType { Name: "integer" } => "0L",
        _ => "default!"
    };

    private static string Ident(string name)
    {
        if (string.IsNullOrEmpty(name))
        {
            return "_";
        }

        var chars = name.Select(ch => char.IsLetterOrDigit(ch) || ch == '_' ? ch : '_').ToArray();
        var clean = char.IsDigit(chars[0]) ? "_" + new string(chars) : new string(chars);
        return Keywords.Contains(clean) ? "@" + clean : clean;
    }
}

file static class ParameterLimits
{
    public static bool ScopeOrPattern(this IrParameter parameter) =>
        parameter.Pattern is not null || parameter.ValidateTest is not null || parameter.Alias is not null;
}
