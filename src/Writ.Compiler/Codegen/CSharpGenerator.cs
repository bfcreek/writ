using System.Globalization;
using System.Text;
using Writ.Compiler.Ir;

namespace Writ.Compiler.Codegen;

/// <summary>
/// Emits a C# static class from the IR subset backed by <see cref="Writ.Runtime.Machine"/>.
/// </summary>
public sealed class CSharpGenerator
{
    private static IReadOnlyDictionary<string, IrFunction> CurrentFunctions { get; set; } =
        new Dictionary<string, IrFunction>(StringComparer.Ordinal);
    private static readonly object GenerateGate = new();
    private static readonly HashSet<string> Keywords = new(StringComparer.Ordinal)
    {
        "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked", "class", "const",
        "continue", "decimal", "default", "delegate", "do", "double", "else", "enum", "event", "explicit", "extern",
        "false", "finally", "fixed", "float", "for", "foreach", "goto", "if", "implicit", "in", "int", "interface",
        "internal", "is", "lock", "long", "namespace", "new", "null", "object", "operator", "out", "override",
        "params", "private", "protected", "public", "readonly", "ref", "return", "sbyte", "sealed", "short",
        "sizeof", "stackalloc", "static", "string", "struct", "switch", "this", "throw", "true", "try", "typeof",
        "uint", "ulong", "unchecked", "unsafe", "ushort", "using", "virtual", "void", "volatile", "while",
        "record", "init", "nint", "nuint", "required", "file", "scoped"
    };

    private static readonly HashSet<string> Builtins = new(StringComparer.Ordinal)
    {
        "len", "round", "sum", "append", "str", "int", "decimal", "bool",
        "json", "csv", "env", "homeFolder", "currentFolder", "tempFolder", "scriptFolder", "machineName", "userName"
    };

    /// <summary>
    /// Why this module cannot be a C# library, or null when it can.
    /// The reason starts with "calls " so emission selection can tell a blocker from a constraint.
    /// </summary>
    public static string? Unsupported(IrModule module)
    {
        foreach (var function in module.Functions)
        {
            foreach (var step in function.Body)
            {
                var why = Visit(step);
                if (why is not null)
                {
                    return why;
                }
            }
        }

        return null;
    }

    public string Generate(IrModule module, string? sourcePath = null)
    {
        lock (GenerateGate)
        {
        CurrentFunctions = module.Functions.ToDictionary(function => function.Name, StringComparer.Ordinal);
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("// Generated by Writ compiler");
        if (!string.IsNullOrEmpty(sourcePath))
        {
            sb.AppendLine($"// Source: {sourcePath}");
        }

        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("public static class WritProgram");
        sb.AppendLine("{");
        foreach (var type in module.Types)
        {
            EmitType(sb, type);
            sb.AppendLine();
        }

        foreach (var function in module.Functions)
        {
            EmitFunction(sb, function);
            sb.AppendLine();
        }

        sb.AppendLine("}");
        return sb.ToString();
        }
    }

    private static void EmitType(StringBuilder sb, IrTypeDecl type)
    {
        var name = Ident(type.Name);
        if (type.EnumMembers.Count > 0)
        {
            sb.AppendLine($"    public enum {name}");
            sb.AppendLine("    {");
            foreach (var member in type.EnumMembers)
            {
                sb.AppendLine($"        {Ident(member)},");
            }

            sb.AppendLine("    }");
            return;
        }

        sb.AppendLine($"    public sealed class {name}");
        sb.AppendLine("    {");
        foreach (var field in type.Fields)
        {
            sb.AppendLine($"        public {CsType(field.Type)} {Ident(field.Name)} {{ get; set; }} = {DefaultValue(field.Type)};");
        }

        sb.AppendLine("    }");
    }

    private static void EmitFunction(StringBuilder sb, IrFunction function)
    {
        if (function.IsEntry)
        {
            sb.AppendLine("    [global::Writ.Runtime.MachineEntry]");
        }

        sb.Append("    public static ");
        sb.Append(CsType(function.ReturnType));
        sb.Append(' ');
        sb.Append(Ident(function.Name));
        sb.Append('(');
        sb.Append(string.Join(", ", function.Parameters.Select(FormatParameter)));
        sb.AppendLine(")");
        sb.AppendLine("    {");

        var locals = Locals(function);
        foreach (var local in locals)
        {
            sb.AppendLine($"        {CsType(local.Type)} {Ident(local.Name)} = {DefaultValue(local.Type)};");
        }

        foreach (var step in function.Body)
        {
            EmitStatement(sb, step, 2, function.ReturnType);
        }

        sb.AppendLine("    }");
    }

    private static string FormatParameter(IrParameter parameter)
    {
        var text = $"{CsType(parameter.Type)} {Ident(parameter.Name)}";
        if (parameter.Default is not null)
        {
            text += " = " + Expr(parameter.Default);
        }

        return text;
    }

    private static List<(string Name, IrType Type)> Locals(IrFunction function)
    {
        var loopNames = new HashSet<string>(StringComparer.Ordinal);
        CollectLoopNames(function.Body, loopNames);
        var seen = new HashSet<string>(StringComparer.Ordinal);
        var locals = new List<(string Name, IrType Type)>();
        foreach (var parameter in function.Parameters)
        {
            seen.Add(parameter.Name);
        }

        CollectLocals(function.Body, loopNames, seen, locals);
        return locals;
    }

    private static void CollectLoopNames(IReadOnlyList<IrNode> body, HashSet<string> names)
    {
        foreach (var node in body)
        {
            switch (node)
            {
                case IrForEach loop:
                    names.Add(loop.Iterator);
                    CollectLoopNames(loop.Body, names);
                    break;
                case IrFor loop:
                    names.Add(loop.Name);
                    CollectLoopNames(loop.Body, names);
                    break;
                case IrIf branch:
                    CollectLoopNames(branch.ThenBody, names);
                    if (branch.OtherwiseBody is not null)
                    {
                        CollectLoopNames(branch.OtherwiseBody, names);
                    }

                    break;
                case IrWhile loop:
                    CollectLoopNames(loop.Body, names);
                    break;
                case IrDo loop:
                    CollectLoopNames(loop.Body, names);
                    break;
                case IrLabel label:
                    CollectLoopNames([label.Statement], names);
                    break;
                case IrSwitch branch:
                    foreach (var arm in branch.Arms)
                    {
                        CollectLoopNames(arm.Body, names);
                    }

                    if (branch.Otherwise is not null)
                    {
                        CollectLoopNames(branch.Otherwise, names);
                    }

                    break;
                case IrTry attempt:
                    CollectLoopNames(attempt.Body, names);
                    if (attempt.OnFailure is not null)
                    {
                        CollectLoopNames(attempt.OnFailure, names);
                    }

                    if (attempt.Finally is not null)
                    {
                        CollectLoopNames(attempt.Finally, names);
                    }

                    break;
                case IrSequence sequence:
                    CollectLoopNames(sequence.Steps, names);
                    break;
                case IrSection section:
                    CollectLoopNames(section.Body, names);
                    break;
                case IrData data:
                    CollectLoopNames(data.Body, names);
                    break;
                case IrTrap trap:
                    CollectLoopNames(trap.Body, names);
                    break;
            }
        }
    }

    private static void CollectLocals(
        IReadOnlyList<IrNode> body,
        HashSet<string> loopNames,
        HashSet<string> seen,
        List<(string Name, IrType Type)> locals)
    {
        foreach (var node in body)
        {
            switch (node)
            {
                case IrAssign assign when seen.Add(assign.Name) && !loopNames.Contains(assign.Name):
                    locals.Add((assign.Name, assign.Type));
                    break;
                case IrIf branch:
                    CollectLocals(branch.ThenBody, loopNames, seen, locals);
                    if (branch.OtherwiseBody is not null)
                    {
                        CollectLocals(branch.OtherwiseBody, loopNames, seen, locals);
                    }

                    break;
                case IrWhile loop:
                    CollectLocals(loop.Body, loopNames, seen, locals);
                    break;
                case IrDo loop:
                    CollectLocals(loop.Body, loopNames, seen, locals);
                    break;
                case IrForEach loop:
                    CollectLocals(loop.Body, loopNames, seen, locals);
                    break;
                case IrFor loop:
                    CollectLocals(loop.Body, loopNames, seen, locals);
                    break;
                case IrLabel label:
                    CollectLocals([label.Statement], loopNames, seen, locals);
                    break;
                case IrSwitch branch:
                    foreach (var arm in branch.Arms)
                    {
                        CollectLocals(arm.Body, loopNames, seen, locals);
                    }

                    if (branch.Otherwise is not null)
                    {
                        CollectLocals(branch.Otherwise, loopNames, seen, locals);
                    }

                    break;
                case IrTry attempt:
                    if (seen.Add(attempt.ErrorName))
                    {
                        locals.Add((attempt.ErrorName, IrPrimitiveType.String));
                    }

                    CollectLocals(attempt.Body, loopNames, seen, locals);
                    if (attempt.OnFailure is not null)
                    {
                        CollectLocals(attempt.OnFailure, loopNames, seen, locals);
                    }

                    if (attempt.Finally is not null)
                    {
                        CollectLocals(attempt.Finally, loopNames, seen, locals);
                    }

                    break;
                case IrSequence sequence:
                    CollectLocals(sequence.Steps, loopNames, seen, locals);
                    break;
                case IrSection section:
                    CollectLocals(section.Body, loopNames, seen, locals);
                    break;
                case IrData data:
                    CollectLocals(data.Body, loopNames, seen, locals);
                    break;
                case IrTrap trap:
                    if (seen.Add(trap.ErrorName))
                    {
                        locals.Add((trap.ErrorName, IrPrimitiveType.String));
                    }

                    CollectLocals(trap.Body, loopNames, seen, locals);
                    break;
            }
        }
    }

    private static void EmitStatement(StringBuilder sb, IrNode node, int indent, IrType? functionReturnType = null)
    {
        var pad = new string(' ', indent * 4);
        switch (node)
        {
            case IrAssign assign:
                if (assign.Operator is "++" or "--")
                {
                    sb.AppendLine($"{pad}{Ident(assign.Name)}{assign.Operator};");
                }
                else
                {
                    sb.AppendLine($"{pad}{Ident(assign.Name)} {assign.Operator} {Expr(assign.Value)};");
                }

                break;
            case IrIf branch:
                sb.AppendLine($"{pad}if ({Expr(branch.Condition)})");
                sb.AppendLine($"{pad}{{");
                foreach (var step in branch.ThenBody)
                {
                    EmitStatement(sb, step, indent + 1, functionReturnType);
                }

                if (branch.OtherwiseBody is not null)
                {
                    sb.AppendLine($"{pad}}}");
                    sb.AppendLine($"{pad}else");
                    sb.AppendLine($"{pad}{{");
                    foreach (var step in branch.OtherwiseBody)
                    {
                        EmitStatement(sb, step, indent + 1, functionReturnType);
                    }
                }

                sb.AppendLine($"{pad}}}");
                break;
            case IrWhile loop:
                sb.AppendLine($"{pad}while ({Expr(loop.Condition)})");
                sb.AppendLine($"{pad}{{");
                foreach (var step in loop.Body)
                {
                    EmitStatement(sb, step, indent + 1, functionReturnType);
                }

                sb.AppendLine($"{pad}}}");
                break;
            case IrDo loop:
                sb.AppendLine($"{pad}do");
                sb.AppendLine($"{pad}{{");
                foreach (var step in loop.Body)
                {
                    EmitStatement(sb, step, indent + 1, functionReturnType);
                }

                sb.AppendLine($"{pad}}} while ({(loop.Until ? "!" : "")}({Expr(loop.Condition)}));");
                break;
            case IrForEach loop:
                sb.AppendLine($"{pad}foreach ({ElementType(loop.Collection.Type)} {Ident(loop.Iterator)} in {Expr(loop.Collection)})");
                sb.AppendLine($"{pad}{{");
                foreach (var step in loop.Body)
                {
                    EmitStatement(sb, step, indent + 1, functionReturnType);
                }

                sb.AppendLine($"{pad}}}");
                break;
            case IrFor loop:
                var name = Ident(loop.Name);
                sb.AppendLine($"{pad}for ({CsType(loop.From.Type)} {name} = {Expr(loop.From)}; {name} <= {Expr(loop.To)}; {name}++)");
                sb.AppendLine($"{pad}{{");
                foreach (var step in loop.Body)
                {
                    EmitStatement(sb, step, indent + 1, functionReturnType);
                }

                sb.AppendLine($"{pad}}}");
                break;
            case IrSwitch branch:
                var switchValue = "__writSwitch" + indent.ToString(CultureInfo.InvariantCulture);
                sb.AppendLine($"{pad}var {switchValue} = {Expr(branch.Value)};");
                for (var i = 0; i < branch.Arms.Count; i++)
                {
                    var arm = branch.Arms[i];
                    var condition = string.Join(" || ", arm.Values.Select(value => $"global::Writ.Runtime.Machine.Compare({switchValue}, \"==\", {Expr(value)})"));
                    sb.AppendLine($"{pad}{(i == 0 ? "if" : "else if")} ({condition})");
                    sb.AppendLine($"{pad}{{");
                    foreach (var step in arm.Body)
                    {
                        EmitStatement(sb, step, indent + 1, functionReturnType);
                    }

                    sb.AppendLine($"{pad}}}");
                }

                if (branch.Otherwise is not null)
                {
                    sb.AppendLine($"{pad}else");
                    sb.AppendLine($"{pad}{{");
                    foreach (var step in branch.Otherwise)
                    {
                        EmitStatement(sb, step, indent + 1, functionReturnType);
                    }

                    sb.AppendLine($"{pad}}}");
                }
                break;
            case IrReturn ret:
                sb.AppendLine(ret.Type is IrVoidType
                    ? $"{pad}return;"
                    : $"{pad}return global::Writ.Runtime.Machine.ConvertTo<{CsType(functionReturnType ?? ret.Type)}>({Expr(ret.Value)});");
                break;
            case IrSay say:
                sb.AppendLine($"{pad}global::Writ.Runtime.Machine.Say(string.Join(\" \", new string[] {{ {string.Join(", ", say.Parts.Select(part => $"global::Writ.Runtime.Machine.Text({Expr(part)})"))} }}));");
                break;
            case IrCommand command:
                sb.AppendLine($"{pad}{Command(command)};");
                break;
            case IrCall call:
                sb.AppendLine($"{pad}{Call(call)};");
                break;
            case IrTry attempt:
                sb.AppendLine($"{pad}try");
                sb.AppendLine($"{pad}{{");
                foreach (var step in attempt.Body)
                {
                    EmitStatement(sb, step, indent + 1, functionReturnType);
                }

                if (attempt.OnFailure is not null)
                {
                    sb.AppendLine($"{pad}}}");
                    sb.AppendLine($"{pad}catch (global::System.Exception __writEx)");
                    sb.AppendLine($"{pad}{{");
                    sb.AppendLine($"{pad}    {Ident(attempt.ErrorName)} = __writEx.Message;");
                    foreach (var step in attempt.OnFailure)
                    {
                        EmitStatement(sb, step, indent + 1, functionReturnType);
                    }
                }

                if (attempt.Finally is not null)
                {
                    sb.AppendLine($"{pad}}}");
                    sb.AppendLine($"{pad}finally");
                    sb.AppendLine($"{pad}{{");
                    foreach (var step in attempt.Finally)
                    {
                        EmitStatement(sb, step, indent + 1, functionReturnType);
                    }
                }

                sb.AppendLine($"{pad}}}");
                break;
            case IrSequence sequence:
                foreach (var step in sequence.Steps)
                {
                    EmitStatement(sb, step, indent, functionReturnType);
                }

                break;
            case IrBreak:
                sb.AppendLine(node is IrBreak { Label: { } breakLabel } ? $"{pad}goto {Ident(breakLabel)}_end;" : $"{pad}break;");
                break;
            case IrContinue:
                sb.AppendLine(node is IrContinue { Label: { } continueLabel } ? $"{pad}goto {Ident(continueLabel)};" : $"{pad}continue;");
                break;
            case IrExit exit:
                sb.AppendLine(exit.Code is null ? $"{pad}return;" : $"{pad}throw new global::Writ.Runtime.MachineHaltException(global::Writ.Runtime.Machine.Text({Expr(exit.Code)}));");
                break;
            case IrLabel label:
                sb.AppendLine($"{pad}{Ident(label.Name)}:");
                EmitStatement(sb, label.Statement, indent, functionReturnType);
                sb.AppendLine($"{pad}{Ident(label.Name)}_end:;");
                break;
            case IrTrap:
                break;
            case IrData data:
                foreach (var step in data.Body)
                {
                    EmitStatement(sb, step, indent, functionReturnType);
                }

                break;
            case IrSection section:
                foreach (var step in section.Body)
                {
                    EmitStatement(sb, step, indent, functionReturnType);
                }

                break;
            case IrRedirect redirect:
                sb.AppendLine($"{pad}try");
                sb.AppendLine($"{pad}{{");
                sb.AppendLine($"{pad}    _ = {Expr(redirect.Command)};");
                sb.AppendLine($"{pad}}}");
                sb.AppendLine($"{pad}catch");
                sb.AppendLine($"{pad}{{");
                sb.AppendLine($"{pad}    throw;");
                sb.AppendLine($"{pad}}}");
                break;
            case IrDotSource source:
                sb.AppendLine($"{pad}_ = global::Writ.Runtime.Machine.InvokeScript(global::Writ.Runtime.Machine.Text({Expr(source.Path)}), \"powershell\", null, new global::System.Collections.Generic.Dictionary<string, object?>(), true);");
                break;
            default:
                sb.AppendLine($"{pad}_ = {Expr(node)};");
                break;
        }
    }

    private static string Expr(IrNode node) => node switch
    {
        IrLiteral literal => Literal(literal),
        IrVar { Name: "succeeded" } => "true",
        IrVar { Name: "pipelineItem" } => "__writPipelineItem",
        IrVar variable => Ident(variable.Name),
        IrCall call => Call(call),
        IrFieldAccess access => $"global::Writ.Runtime.Machine.Field<{CsType(access.Type)}>({Expr(access.Target)}, {Quote(access.FieldName)}, {(access.Optional ? "true" : "false")})",
        IrListLiteral list => List(list),
        IrBinary binary => Binary(binary),
        IrUnary unary => unary.Operator switch
        {
            "not" => $"(!({Expr(unary.Operand)}))",
            "bnot" => $"global::Writ.Runtime.Machine.BitwiseNot({Expr(unary.Operand)})",
            _ => $"(-({Expr(unary.Operand)}))"
        },
        IrSumProjection sum => $"global::Writ.Runtime.Machine.SumMap({Expr(sum.Collection)}, {Ident(sum.Iterator)} => {Expr(sum.Projection)})",
        IrFilter filter => $"global::Writ.Runtime.Machine.Filter({Expr(filter.Collection)}, {Ident(filter.Iterator)} => {Expr(filter.Predicate)})",
        IrCapabilityCall capability => Capability(capability),
        IrValidate validate => Validate(validate),
        IrRetry retry => $"global::Writ.Runtime.Machine.Retry(() => {Expr(retry.Operation)}, {retry.Times.ToString(CultureInfo.InvariantCulture)})",
        IrSort sort => $"global::Writ.Runtime.Machine.Sort({Expr(sort.Collection)}, {Quote(sort.Field)}, {(sort.Descending ? "true" : "false")})",
        IrTake take => $"global::Writ.Runtime.Machine.Take({Expr(take.Collection)}, {Expr(take.Count)})",
        IrSelectField select => $"global::Writ.Runtime.Machine.SelectField<{ElementType(select.Type)}>({Expr(select.Collection)}, {Quote(select.Field)})",
        IrScriptCall script => ScriptCall(script),
        IrSequence sequence => Sequence(sequence),
        IrCommand command => Command(command),
        _ => throw new InvalidOperationException($"Cannot emit {node.GetType().Name}.")
    };

    private static string Call(IrCall call)
    {
        if (call.IsBuiltin)
        {
            var args = call.Arguments.Select(Expr).ToList();
            return call.Callee switch
            {
                "len" => $"global::Writ.Runtime.Machine.Len({args[0]})",
                "round" => $"global::Writ.Runtime.Machine.Round({args[0]}, {args[1]})",
                "sum" => $"global::Writ.Runtime.Machine.Sum({args[0]})",
                "append" => $"global::Writ.Runtime.Machine.Append({args[0]}, {args[1]})",
                "str" => $"global::Writ.Runtime.Machine.Text({args[0]})",
                "int" => $"global::Writ.Runtime.Machine.ToInteger({args[0]})",
                "decimal" => $"global::Writ.Runtime.Machine.ToDecimal({args[0]})",
                "bool" => $"global::Writ.Runtime.Machine.ToBoolean({args[0]})",
                "json" => $"global::Writ.Runtime.Machine.ParseJson({args[0]})",
                "csv" => $"global::Writ.Runtime.Machine.ParseCsv({args[0]})",
                "env" => $"global::Writ.Runtime.Machine.Env({args[0]})",
                "homeFolder" => "global::Writ.Runtime.Machine.HomeFolder()",
                "currentFolder" => "global::Writ.Runtime.Machine.CurrentFolder()",
                "tempFolder" => "global::Writ.Runtime.Machine.TempFolder()",
                "scriptFolder" => "global::Writ.Runtime.Machine.ScriptDirectory",
                "machineName" => "global::Writ.Runtime.Machine.MachineName()",
                "userName" => "global::Writ.Runtime.Machine.UserName()",
                _ => ConstructCall(call, args) ?? throw new InvalidOperationException($"Cannot emit builtin {call.Callee}.")
            };
        }

        var passedArgs = call.Arguments.Select((argument, index) =>
            CurrentFunctions.TryGetValue(call.Callee, out var function) && index < function.Parameters.Count
                ? $"global::Writ.Runtime.Machine.ConvertTo<{CsType(function.Parameters[index].Type)}>({Expr(argument)})"
                : Expr(argument)).ToList();
        return $"{Ident(call.Callee)}({string.Join(", ", passedArgs)})";
    }

    private static string? ConstructCall(IrCall call, IReadOnlyList<string> args)
    {
        string Arg(int index) => args[index];
        string LiteralText(int index, string fallback = "") => call.Arguments[index] is IrLiteral { Value: string text } ? text : fallback;
        return call.Callee switch
        {
            "range" when args.Count == 2 => $"global::Writ.Runtime.Machine.Range({Arg(0)}, {Arg(1)})",
            "index" when args.Count == 2 => $"global::Writ.Runtime.Machine.ConvertTo<{CsType(call.Type)}>(global::Writ.Runtime.Machine.Index({Arg(0)}, {Arg(1)}))",
            "slice" when args.Count == 3 => $"global::Writ.Runtime.Machine.ConvertTo<{CsType(call.Type)}>(global::Writ.Runtime.Machine.Slice({Arg(0)}, {Arg(1)}, {Arg(2)}))",
            "join" when args.Count == 1 => $"global::Writ.Runtime.Machine.Join({Arg(0)})",
            "join" when args.Count == 2 => $"global::Writ.Runtime.Machine.Join({Arg(0)}, global::Writ.Runtime.Machine.Text({Arg(1)}))",
            "split" => $"global::Writ.Runtime.Machine.Split({Arg(0)}, {Arg(1)})",
            "format" => $"global::Writ.Runtime.Machine.Format({Arg(0)}, {string.Join(", ", args.Skip(1))})",
            "replace" => $"global::Writ.Runtime.Machine.Replace({Arg(0)}, {Arg(1)}, {Arg(2)})",
            "like" => $"global::Writ.Runtime.Machine.Like({Arg(0)}, {Arg(1)})",
            "notlike" => $"(!global::Writ.Runtime.Machine.Like({Arg(0)}, {Arg(1)}))",
            "match" => $"global::Writ.Runtime.Machine.Match({Arg(0)}, {Arg(1)})",
            "notmatch" => $"(!global::Writ.Runtime.Machine.Match({Arg(0)}, {Arg(1)}))",
            "contains" => $"global::Writ.Runtime.Machine.Contains({Arg(0)}, {Arg(1)})",
            "notcontains" => $"(!global::Writ.Runtime.Machine.Contains({Arg(0)}, {Arg(1)}))",
            "in" => $"global::Writ.Runtime.Machine.In({Arg(0)}, {Arg(1)})",
            "notin" => $"(!global::Writ.Runtime.Machine.In({Arg(0)}, {Arg(1)}))",
            "xor" => $"global::Writ.Runtime.Machine.Xor({Arg(0)}, {Arg(1)})",
            "band" => $"global::Writ.Runtime.Machine.BitwiseAnd({Arg(0)}, {Arg(1)})",
            "bor" => $"global::Writ.Runtime.Machine.BitwiseOr({Arg(0)}, {Arg(1)})",
            "bxor" => $"global::Writ.Runtime.Machine.BitwiseXor({Arg(0)}, {Arg(1)})",
            "bnot" => $"global::Writ.Runtime.Machine.BitwiseNot({Arg(0)})",
            "shl" => $"global::Writ.Runtime.Machine.ShiftLeft({Arg(0)}, {Arg(1)})",
            "shr" => $"global::Writ.Runtime.Machine.ShiftRight({Arg(0)}, {Arg(1)})",
            "is" => $"global::Writ.Runtime.Machine.Is({Arg(0)}, {Quote(LiteralText(1))})",
            "isnot" => $"(!global::Writ.Runtime.Machine.Is({Arg(0)}, {Quote(LiteralText(1))}))",
            "as" => $"global::Writ.Runtime.Machine.ConvertTo<{CsType(call.Type)}>(global::Writ.Runtime.Machine.As({Arg(0)}, {Quote(LiteralText(1))}))",
            "cast" => $"global::Writ.Runtime.Machine.ConvertTo<{CsType(call.Type)}>(global::Writ.Runtime.Machine.Cast({Arg(0)}, {Quote(LiteralText(1))}))",
            "coalesce" => $"global::Writ.Runtime.Machine.ConvertTo<{CsType(call.Type)}>(global::Writ.Runtime.Machine.Coalesce({Arg(0)}, {Arg(1)}))",
            "ternary" => $"({Arg(1)} ? {Arg(0)} : {Arg(2)})",
            "andThen" => $"({Arg(0)} && {Arg(1)})",
            "orElse" => $"({Arg(0)} || {Arg(1)})",
            "hash" => $"global::Writ.Runtime.Machine.Hash({string.Join(", ", args.Skip(1))})",
            "block" => $"new global::System.Func<object?, object?>(__writPipelineItem => {Arg(0)})",
            "output" => Arg(0),
            "collected" => $"global::Writ.Runtime.Machine.ConvertTo<{CsType(call.Type)}>({Arg(0)})",
            "pipe" when call.Arguments.Count == 2 && call.Arguments[1] is IrCall { Callee: "block" } => $"global::Writ.Runtime.Machine.Pipe({Arg(0)}, {Arg(1)})",
            "static" => $"global::Writ.Runtime.Machine.ConvertTo<{CsType(call.Type)}>(global::Writ.Runtime.Machine.Static({Arg(0)}, {Arg(1)}{(args.Count > 2 ? ", " + string.Join(", ", args.Skip(2)) : "")}))",
            "member" => $"global::Writ.Runtime.Machine.ConvertTo<{CsType(call.Type)}>(global::Writ.Runtime.Machine.Member({Arg(0)}, {Arg(1)}{(args.Count > 2 ? ", " + string.Join(", ", args.Skip(2)) : "")}))",
            "grid" => $"global::Writ.Runtime.Machine.Grid({Arg(0)}, {Arg(1)})",
            "char" or "float" or "pattern" or "xml" or "object" => $"global::Writ.Runtime.Machine.ConvertTo<{CsType(call.Type)}>(global::Writ.Runtime.Machine.Cast({Arg(0)}, {Quote(call.Callee)}))",
            _ => null
        };
    }

    private static string Command(IrCommand command)
    {
        string? Arg(string name) => command.Arguments.FirstOrDefault(argument => argument.Name == name) is { } found
            ? Expr(found.Value)
            : null;

        return command.Name switch
        {
            "Clear-Host" => "global::Writ.Runtime.Machine.Clear()",
            "Read-Host" => $"global::Writ.Runtime.Machine.Read({Arg("Prompt") ?? "null"})",
            "Start-Sleep" when Arg("Milliseconds") is { } milliseconds => $"global::Writ.Runtime.Machine.Wait({milliseconds}, true)",
            "Start-Sleep" when Arg("Seconds") is { } seconds => $"global::Writ.Runtime.Machine.Wait({seconds}, false)",
            "throw" => $"throw new global::Writ.Runtime.MachineHaltException(global::Writ.Runtime.Machine.Text({(command.Arguments.Count == 0 ? "\"\"" : Expr(command.Arguments[0].Value))}))",
            _ => command.Type is IrVoidType
                ? $"global::Writ.Runtime.Machine.InvokeCommand({Quote(command.Name)}, {Arguments(command.Arguments)})"
                : $"global::Writ.Runtime.Machine.ConvertTo<{CsType(command.Type)}>(global::Writ.Runtime.Machine.InvokeCommand({Quote(command.Name)}, {Arguments(command.Arguments)}))"
        };
    }

    private static string Capability(IrCapabilityCall capability)
    {
        var writes = capability.Effects.Any(Writes) ? "true" : "false";
        var call = $"global::Writ.Runtime.Machine.InvokeCapability({Quote(capability.Alias)}, {Quote(capability.Operation)}, {Quote(capability.ManifestPath)}, {Arguments(capability.Arguments)}, {Quote(capability.Provider)}, {Quote(capability.Endpoint ?? "")}, {Quote(string.IsNullOrEmpty(capability.Transport) ? "stdio" : capability.Transport)}, {Quote(capability.WorkingDirectory ?? "")}, {writes})";
        return capability.Type is IrVoidType ? call : $"global::Writ.Runtime.Machine.ConvertTo<{CsType(capability.Type)}>({call})";
    }

    private static string ScriptCall(IrScriptCall script)
    {
        var writes = script.Effects.Any(Writes) ? "true" : "false";
        var call = $"global::Writ.Runtime.Machine.InvokeScript({Quote(script.Path)}, {Quote(script.Kind)}, {Quote(script.CompiledScript ?? "")}, {Arguments(script.Arguments)}, {writes})";
        return script.Type is IrVoidType ? call : $"global::Writ.Runtime.Machine.ConvertTo<{CsType(script.Type)}>({call})";
    }

    private static string Validate(IrValidate validate)
    {
        if (validate.Type is IrRecordType record)
        {
            return $"global::Writ.Runtime.Machine.Validate<{CsType(validate.Type)}>({Expr(validate.Value)}, {Quote(record.Name)}, {string.Join(", ", record.Fields.Select(field => Quote(field.Name)))})";
        }

        if (validate.Type is IrListType { ElementType: IrRecordType elementRecord })
        {
            return $"global::Writ.Runtime.Machine.ConvertTo<{CsType(validate.Type)}>(global::Writ.Runtime.Machine.Validate({Expr(validate.Value)}, {Quote(elementRecord.Name)}, {string.Join(", ", elementRecord.Fields.Select(field => Quote(field.Name)))}) )";
        }

        return $"global::Writ.Runtime.Machine.ConvertTo<{CsType(validate.Type)}>({Expr(validate.Value)})";
    }

    private static string Sequence(IrSequence sequence)
    {
        if (sequence.Steps.Count == 0)
        {
            return "null";
        }

        var sb = new StringBuilder("new global::System.Func<object?>(() => { ");
        for (var i = 0; i < sequence.Steps.Count; i++)
        {
            if (i == sequence.Steps.Count - 1)
            {
                sb.Append("return ");
                sb.Append(Expr(sequence.Steps[i]));
                sb.Append("; ");
            }
            else
            {
                sb.Append("_ = ");
                sb.Append(Expr(sequence.Steps[i]));
                sb.Append("; ");
            }
        }

        sb.Append("})()");
        return $"global::Writ.Runtime.Machine.ConvertTo<{CsType(sequence.Type)}>({sb})";
    }

    private static string Arguments(IReadOnlyList<IrNamedArgument> arguments)
    {
        if (arguments.Count == 0)
        {
            return "new global::System.Collections.Generic.Dictionary<string, object?>()";
        }

        return "new global::System.Collections.Generic.Dictionary<string, object?> { " +
               string.Join(", ", arguments.Select(argument => $"[{Quote(argument.Name)}] = {Expr(argument.Value)}")) +
               " }";
    }

    private static bool Writes(EffectKind effect) =>
        effect is EffectKind.FileSystemWrite or EffectKind.ExternalState or EffectKind.NetworkWrite or EffectKind.Script or EffectKind.RuntimeAi;

    private static string List(IrListLiteral list)
    {
        var type = CsType(list.Type);
        if (list.Elements.Count == 0)
        {
            return $"new {type}()";
        }

        return $"new {type} {{ {string.Join(", ", list.Elements.Select(Expr))} }}";
    }

    private static string Binary(IrBinary binary)
    {
        if (binary.Operator == "+" && binary.Left.Type is IrListType && binary.Right.Type is IrListType)
        {
            return $"global::Writ.Runtime.Machine.Concat({Expr(binary.Left)}, {Expr(binary.Right)})";
        }

        if (binary.Operator == "*" && binary.Left.Type is IrListType)
        {
            return $"global::Writ.Runtime.Machine.Repeat({Expr(binary.Left)}, {Expr(binary.Right)})";
        }

        if (binary.Operator == "*" && binary.Left.Type is IrPrimitiveType { Name: "string" })
        {
            return $"global::Writ.Runtime.Machine.Repeat({Expr(binary.Left)}, {Expr(binary.Right)})";
        }

        if (binary.Type is IrPrimitiveType { Name: "string" })
        {
            return $"(global::Writ.Runtime.Machine.Text({Expr(binary.Left)}) + global::Writ.Runtime.Machine.Text({Expr(binary.Right)}))";
        }

        var op = binary.Operator switch
        {
            "and" => "&&",
            "or" => "||",
            _ => binary.Operator
        };
        if (op is "==" or "!=" or "<" or "<=" or ">" or ">=")
        {
            return $"global::Writ.Runtime.Machine.Compare({Expr(binary.Left)}, {Quote(op)}, {Expr(binary.Right)})";
        }

        if (binary.Type is IrPrimitiveType { Name: "decimal" } && op is "+" or "-" or "*" or "/" or "%")
        {
            return $"((decimal)({Expr(binary.Left)}) {op} (decimal)({Expr(binary.Right)}))";
        }

        return $"({Expr(binary.Left)} {op} {Expr(binary.Right)})";
    }

    private static string Literal(IrLiteral literal) => literal.Value switch
    {
        null => "null",
        long number => number < 0 ? $"({number.ToString(CultureInfo.InvariantCulture)}L)" : $"{number.ToString(CultureInfo.InvariantCulture)}L",
        int number => number < 0 ? $"({number.ToString(CultureInfo.InvariantCulture)}L)" : $"{number.ToString(CultureInfo.InvariantCulture)}L",
        decimal number => DecimalLiteral(number),
        string text => Quote(text),
        bool flag => flag ? "true" : "false",
        _ => throw new InvalidOperationException($"Cannot emit literal {literal.Value}.")
    };

    private static string DecimalLiteral(decimal number)
    {
        var text = number.ToString(CultureInfo.InvariantCulture);
        var literal = text.IndexOfAny(['.', 'E', 'e']) >= 0 ? text + "m" : text + "m";
        return number < 0 ? $"({literal})" : literal;
    }

    private static string Quote(string text)
    {
        var sb = new StringBuilder("\"");
        foreach (var ch in text)
        {
            switch (ch)
            {
                case '\\':
                    sb.Append("\\\\");
                    break;
                case '"':
                    sb.Append("\\\"");
                    break;
                case '\n':
                    sb.Append("\\n");
                    break;
                case '\r':
                    sb.Append("\\r");
                    break;
                case '\t':
                    sb.Append("\\t");
                    break;
                default:
                    if (char.IsControl(ch))
                    {
                        sb.Append("\\u");
                        sb.Append(((int)ch).ToString("x4", CultureInfo.InvariantCulture));
                    }
                    else
                    {
                        sb.Append(ch);
                    }

                    break;
            }
        }

        sb.Append('"');
        return sb.ToString();
    }

    private static string? Visit(IrNode node)
    {
        switch (node)
        {
            case IrAssign assign:
                if (assign.Operator != "=" || !string.IsNullOrEmpty(assign.Scope) || assign.Option is not null)
                {
                    return "calls an assignment this library does not emit";
                }

                return Visit(assign.Value);
            case IrIf branch:
                return Visit(branch.Condition) ?? VisitAll(branch.ThenBody) ?? VisitAll(branch.OtherwiseBody);
            case IrWhile loop:
                return Visit(loop.Condition) ?? VisitAll(loop.Body);
            case IrForEach loop:
                return Visit(loop.Collection) ?? VisitAll(loop.Body);
            case IrFor loop:
                return Visit(loop.From) ?? Visit(loop.To) ?? VisitAll(loop.Body);
            case IrReturn ret:
                return ret.Type is IrVoidType ? null : Visit(ret.Value);
            case IrSay say:
                return VisitAll(say.Parts);
            case IrLiteral:
                return null;
            case IrVar variable:
                if (!string.IsNullOrEmpty(variable.Scope) || variable.Name is "this" or "pipelineItem" or "arguments" or "errors" or "succeeded")
                {
                    return $"calls {variable.Name}";
                }

                return null;
            case IrCall call:
                if (call.IsBuiltin && !Builtins.Contains(call.Callee))
                {
                    return $"calls {call.Callee}";
                }

                return VisitAll(call.Arguments);
            case IrFieldAccess access:
                return Visit(access.Target);
            case IrListLiteral list:
                return VisitAll(list.Elements);
            case IrBinary binary:
                if (binary.Operator is not ("+" or "-" or "*" or "/" or "%" or "==" or "!=" or "<" or "<=" or ">" or ">=" or "and" or "or"))
                {
                    return $"calls operator {binary.Operator}";
                }

                return Visit(binary.Left) ?? Visit(binary.Right);
            case IrUnary unary:
                if (unary.Operator is not ("not" or "-"))
                {
                    return $"calls operator {unary.Operator}";
                }

                return Visit(unary.Operand);
            case IrCommand command:
                return VisitAll(command.Arguments.Select(argument => argument.Value));
            case IrSumProjection sum:
                return Visit(sum.Collection) ?? Visit(sum.Projection);
            case IrFilter filter:
                return Visit(filter.Collection) ?? Visit(filter.Predicate);
            case IrCapabilityCall capability:
                return VisitAll(capability.Arguments.Select(argument => argument.Value));
            case IrSequence sequence:
                return VisitAll(sequence.Steps);
            case IrSort sort:
                return Visit(sort.Collection);
            case IrTake take:
                return Visit(take.Collection) ?? Visit(take.Count);
            case IrSelectField select:
                return Visit(select.Collection);
            case IrValidate validate:
                return Visit(validate.Value);
            case IrRetry retry:
                return Visit(retry.Operation);
            case IrScriptCall script:
                return VisitAll(script.Arguments.Select(argument => argument.Value));
            case IrTry attempt:
                return VisitAll(attempt.Body) ?? VisitAll(attempt.OnFailure) ?? VisitAll(attempt.Finally);
            case IrBreak or IrContinue or IrExit:
                return null;
            default:
                return $"calls {node.GetType().Name}";
        }
    }

    private static string? VisitAll(IEnumerable<IrNode>? nodes)
    {
        if (nodes is null)
        {
            return null;
        }

        foreach (var node in nodes)
        {
            var why = Visit(node);
            if (why is not null)
            {
                return why;
            }
        }

        return null;
    }

    private static string ElementType(IrType type) =>
        type is IrListType list ? CsType(list.ElementType) : "object";

    private static string CsType(IrType type) => type switch
    {
        IrPrimitiveType { Name: "integer" } => "long",
        IrPrimitiveType { Name: "decimal" } => "decimal",
        IrPrimitiveType { Name: "string" } => "string",
        IrPrimitiveType { Name: "boolean" } => "bool",
        IrPrimitiveType { Name: "null" } => "object?",
        IrListType list => $"global::System.Collections.Generic.List<{CsType(list.ElementType)}>",
        IrRecordType record => Ident(record.Name),
        IrDynamicType => "object?",
        IrVoidType => "void",
        _ => "object"
    };

    private static string DefaultValue(IrType type) => type switch
    {
        IrListType => $"new {CsType(type)}()",
        IrPrimitiveType { Name: "string" } => "\"\"",
        IrPrimitiveType { Name: "boolean" } => "false",
        IrPrimitiveType { Name: "decimal" } => "0m",
        IrPrimitiveType { Name: "integer" } => "0L",
        _ => "default!"
    };

    private static string Ident(string name)
    {
        if (string.IsNullOrEmpty(name))
        {
            return "_";
        }

        var chars = name.Select(ch => char.IsLetterOrDigit(ch) || ch == '_' ? ch : '_').ToArray();
        var clean = char.IsDigit(chars[0]) ? "_" + new string(chars) : new string(chars);
        return Keywords.Contains(clean) ? "@" + clean : clean;
    }
}

